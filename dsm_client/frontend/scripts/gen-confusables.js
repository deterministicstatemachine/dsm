#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
// Writes src/domain/confusables.ts from Unicode's confusables.txt (UTS #39,
// Unicode Security Mechanisms), the table name comparison reads characters
// by. Run it on the file https://www.unicode.org/Public/security/<version>/confusables.txt:
//
//   node scripts/gen-confusables.js path/to/confusables.txt
//
// Each data line is `source ; prototype ; MA # comment`, the source one code
// point and the prototype one or more, all in Unicode's hexadecimal notation.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const input = process.argv[2];
if (input === undefined) {
  console.error('usage: node scripts/gen-confusables.js path/to/confusables.txt');
  process.exit(2);
}

const text = fs.readFileSync(input, 'utf8');
const version = /^# Version: (\S+)$/m.exec(text);
if (version === null) throw new Error(`${input} names no version: not Unicode's confusables.txt`);
const sha256 = crypto.createHash('sha256').update(fs.readFileSync(input)).digest('hex');

const rows = [];
for (const line of text.split('\n')) {
  const data = line.replace(/#.*$/, '').trim();
  if (data.length === 0) continue;
  const fields = data.split(';').map((f) => f.trim());
  if (fields.length !== 3 || fields[2] !== 'MA') throw new Error(`unreadable line: ${line}`);
  const source = fields[0].split(/\s+/).map((h) => parseInt(h, 16));
  const prototype = fields[1].split(/\s+/).map((h) => parseInt(h, 16));
  if (source.length !== 1) throw new Error(`a source of ${source.length} code points: ${line}`);
  rows.push([source[0], ...prototype]);
}
rows.sort((a, b) => a[0] - b[0]);

const out = [
  '// SPDX-License-Identifier: Apache-2.0',
  `// Unicode ${version[1]} confusables.txt (UTS #39), generated by scripts/gen-confusables.js`,
  `// from the file whose SHA-256 is ${sha256}.`,
  '// Each row is a code point, then the code points of its prototype: the',
  '// characters it is read as. Regenerate it; do not edit it.',
  '',
  'export const CONFUSABLES: readonly (readonly number[])[] = [',
  ...rows.map((r) => `  [${r.join(', ')}],`),
  '];',
  '',
].join('\n');

const target = path.join(__dirname, '..', 'src', 'domain', 'confusables.ts');
fs.writeFileSync(target, out);
console.log(`${rows.length} rows of Unicode ${version[1]} confusables written to ${path.relative(process.cwd(), target)}`);
