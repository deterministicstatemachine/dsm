/// §16.6 defect zero: per-step EK material captured at signing time and written
/// LATER, inside the single pre-submit transaction.
///
/// `expected_prev` is the committed Local cert head as it stood BEFORE signing.
/// The acceptance finalizer also advances cert heads, so the durable write CASes
/// against this snapshot: if the head moved in between, the whole commit aborts
/// while nothing has been sent yet — the only point at which losing that race is
/// still free.
struct PendingEkMaterial {
    ek_pk: Vec<u8>,
    ek_sk: Vec<u8>,
    at_rest_key: [u8; 32],
    is_init: bool,
    expected_prev: Option<Vec<u8>>,
    is_first_ek_step: bool,
}

/// Everything an online send determines before anything becomes deliverable.
///
/// Produced by the synchronous builder that runs between the pure advance
/// preparation and the durable write, then committed — in full — inside the same
/// SQLite transaction as the canonical advance. No partial combination of these
/// is a valid state.
struct OnlineSendArtifacts {
    sender_proposal: crate::storage::client_db::SenderOnlineProposal,
    outbox_record: crate::storage::client_db::SenderOutboxRecord,
    /// Deterministic in the receipt commitment; equals the node message id.
    submission_id: String,
    /// Per-step EK material captured during signing, written with the bundle.
    ek_material: PendingEkMaterial,
    /// Canonical receipt bytes, retained for the acceptance-reply path.
    receipt_canonical_bytes: Vec<u8>,
    /// ADR 0003: every OTHER frozen artifact this send will emit, already
    /// encoded. Persisted in the SAME transaction as everything above.
    extra_artifacts: Vec<crate::storage::client_db::SenderOutboxArtifact>,
}

impl AppRouterImpl {
    async fn repair_contact_identity_from_directory(
        &self,
        contact_record: crate::storage::client_db::ContactRecord,
        entry: &dsm::core::identity::directory::DirectoryEntry,
    ) -> Result<crate::storage::client_db::ContactRecord, String> {
        let alias = contact_record.alias.clone();
        let old_genesis = contact_record.genesis_hash.clone();

        // The trust decision — AK guard, ML-KEM binding verification, and record synthesis — is a
        // pure, I/O-free function. `store_contact` below is UNREACHABLE unless it returns
        // `Repaired`, so a future refactor cannot slip a persist ahead of the guard/verify: the only
        // way to reach persistence is for the decision to have already accepted the material.
        match repair_contact_decision(contact_record, entry)? {
            ContactRepair::Unchanged(record) => Ok(record),
            ContactRepair::Repaired(record) => {
                log::warn!(
                    "[wallet.send] repairing stale contact identity alias={} genesis_old={} genesis_new={}",
                    alias,
                    crate::util::text_id::encode_base32_crockford(&old_genesis)
                        .get(..8)
                        .unwrap_or("?"),
                    crate::util::text_id::encode_base32_crockford(&record.genesis_hash)
                        .get(..8)
                        .unwrap_or("?"),
                );

                crate::storage::client_db::store_contact(&record)
                    .map_err(|e| format!("failed to persist repaired contact identity: {e}"))?;

                let verified = record
                    .to_verified_contact()
                    .map_err(|e| format!("repaired contact identity is malformed: {e}"))?;
                let mut cm = self.contact_manager.clone();
                cm.restore_contact_from_storage(verified)
                    .await
                    .map_err(|e| format!("failed to refresh in-memory contact identity: {e}"))?;

                Ok(record)
            }
        }
    }

    pub fn new(config: SdkConfig) -> Result<Self, dsm::types::error::DsmError> {
        // Device identity MUST come from persisted AppState (post-genesis). Any alternate path
        // hashing would route online transfers to the wrong inbox. Abort early if the
        // persisted device id is missing or malformed to avoid silent misrouting.
        let device_id_bytes: [u8; 32] = match crate::sdk::app_state::AppState::get_device_id() {
            Some(dev) if dev.len() == 32 => {
                let mut a = [0u8; 32];
                a.copy_from_slice(&dev);
                a
            }
            Some(dev) => {
                return Err(dsm::types::error::DsmError::InvalidState(
                    format!("AppState device_id length {} != 32. Regenerate identity before starting AppRouter.", dev.len())
                ));
            }
            None => {
                return Err(dsm::types::error::DsmError::InvalidState(
                    "AppState device_id missing. Run genesis/identity setup before AppRouter init."
                        .to_string(),
                ));
            }
        };

        let genesis_hash_bytes: [u8; 32] = match crate::sdk::app_state::AppState::get_genesis_hash()
        {
            Some(gen) if gen.len() == 32 => {
                let mut a = [0u8; 32];
                a.copy_from_slice(&gen);
                a
            }
            Some(gen) => {
                return Err(dsm::types::error::DsmError::InvalidState(
                    format!("AppState genesis_hash length {} != 32. Regenerate identity before starting AppRouter.", gen.len())
                ));
            }
            None => {
                return Err(dsm::types::error::DsmError::InvalidState(
                    "AppState genesis_hash missing. Run genesis/identity setup before AppRouter init.".to_string()
                ));
            }
        };

        let cm = ContactManager::open(device_id_bytes, genesis_hash_bytes)?;

        // Canonical device id text (base32) used for BOTH local storage keys and online transport.
        // Strict: no dotted-decimal anywhere.
        let device_id_b32_for_storage =
            crate::util::text_id::encode_base32_crockford(&device_id_bytes);

        // CoreSDK init uses the persisted device identity.
        // Note: AppRouterImpl is only installed AFTER genesis creation via BootstrapAdapter.
        // Genesis state must exist before this constructor is called (MPC flow enforces this).
        let public_key = crate::sdk::app_state::AppState::get_public_key().ok_or_else(|| {
            dsm::types::error::DsmError::InvalidState(
                "AppState public_key missing. Run genesis/identity setup before AppRouter init."
                    .to_string(),
            )
        })?;
        let device_info = DeviceInfo::new(device_id_bytes, public_key);
        let core = match crate::sdk::core_sdk::CoreSDK::new_with_device(device_info) {
            Ok(c) => std::sync::Arc::new(c),
            Err(e) => {
                return Err(dsm::types::error::DsmError::InvalidState(format!(
                    "CoreSDK::new_with_device() failed (genesis state missing or corrupt): {:?}",
                    e
                )));
            }
        };
        if core.device_head().is_none() {
            return Err(dsm::types::error::DsmError::InvalidState(
                "no device head: install the wallet's genesis before AppRouter init".to_string(),
            ));
        }
        log::info!(
            "[DSM_SDK] AppRouter local device_id(b32)={}",
            device_id_b32_for_storage
        );
        let wallet = match WalletSDK::new(core.clone(), &device_id_b32_for_storage, None) {
            Ok(w) => Arc::new(w),
            Err(e) => {
                return Err(dsm::types::error::DsmError::InvalidState(format!(
                    "WalletSDK::new() failed (genesis state missing or corrupt): {:?}",
                    e
                )));
            }
        };

        // Publish the wallet's Kyber public key (derived from Smaster when the wallet was
        // built) to the bridge slot, so the bilateral BLE prepare exchange attaches it.
        crate::bridge::install_local_kyber_pubkey(wallet.get_kyber_public_key()?);

        // ✅ CRITICAL: Initialize bilateral chains for all restored contacts
        // This ensures online transfers can find the bilateral chain tip for existing contacts.
        {
            use crate::storage::client_db::get_all_contacts;
            match get_all_contacts() {
                Ok(contacts) => {
                    log::info!(
                        "[DSM_SDK] 🔗 Initializing bilateral chains for {} contacts",
                        contacts.len()
                    );
                    for record in contacts {
                        if record.device_id.len() == 32 && record.genesis_hash.len() == 32 {
                            let device_id_b32 =
                                crate::util::text_id::encode_base32_crockford(&record.device_id);
                            let initial_tip = relationship_tip_for_contact_restore(
                                device_id_bytes,
                                genesis_hash_bytes,
                                &record,
                            )
                            .unwrap_or([0u8; 32]);
                            match wallet.initialize_bilateral_chain(&device_id_b32, &initial_tip) {
                                Ok(tip) => {
                                    log::debug!(
                                        "[DSM_SDK] ✅ Bilateral chain initialized for {} (chain_tip_id={})",
                                        record.alias,
                                        base32::encode(base32::Alphabet::Crockford, &tip.chain_tip_id)
                                    );
                                }
                                Err(e) => {
                                    log::warn!(
                                        "[DSM_SDK] ⚠️ Failed to init bilateral chain for {}: {}",
                                        record.alias,
                                        e
                                    );
                                }
                            }
                        }
                    }
                    log::info!("[DSM_SDK] ✅ Bilateral chain initialization complete");
                }
                Err(e) => {
                    log::warn!(
                        "[DSM_SDK] ⚠️ Could not init bilateral chains (contacts load failed): {}",
                        e
                    );
                }
            }
        }

        // Initialize Bitcoin Tap (dBTC) key store from device identity.
        // device_id_bytes is a 32-byte hash derived deterministically from device_entropy,
        // so the same device always produces the same Bitcoin keys.
        let btc_network = crate::sdk::runtime_config::RuntimeConfig::get_bitcoin_network();
        let mut bitcoin_keys = crate::sdk::bitcoin_key_store::BitcoinKeyStore::from_entropy(
            &device_id_bytes,
            btc_network,
        )
        .map_err(|e| {
            dsm::types::error::DsmError::InvalidState(format!("BitcoinKeyStore init failed: {e}"))
        })?;

        if let Ok(Some(active_account)) = crate::storage::client_db::get_active_bitcoin_account() {
            let secret =
                String::from_utf8(active_account.secret_material.clone()).map_err(|_| {
                    dsm::types::error::DsmError::InvalidState(
                        "Active Bitcoin account secret material is not UTF-8".to_string(),
                    )
                })?;
            let network = Self::bitcoin_network_from_u32(active_account.network);
            match Self::keystore_from_import(&active_account.import_kind, &secret, network) {
                Ok(mut restored) => {
                    // Restore address index from DB so balance scan covers all UTXOs
                    // (fixes the Index-0 Trap where next_receive_index resets to 0 on restart).
                    restored.set_receive_index(active_account.active_receive_index);
                    bitcoin_keys = restored;
                    log::info!(
                        "[bitcoin.wallet] restored active account {} ({}) active_receive_index={}",
                        active_account.account_id,
                        active_account.import_kind,
                        active_account.active_receive_index
                    );
                }
                Err(e) => {
                    log::warn!(
                        "[bitcoin.wallet] failed to restore active account {}: {}",
                        active_account.account_id,
                        e
                    );
                }
            }
        }

        let dlv_manager = Arc::new(dsm::vault::DLVManager::new());
        let bitcoin_tap = Arc::new(crate::sdk::bitcoin_tap_sdk::BitcoinTapSdk::new(dlv_manager));

        Ok(Self {
            _config: config,
            contact_manager: cm,
            wallet,
            core_sdk: core,
            device_id_bytes,
            bitcoin_keys: Arc::new(Mutex::new(bitcoin_keys)),
            bitcoin_tap,
            bitcoin_tap_restored: tokio::sync::OnceCell::new(),
            policy_cache: Mutex::new(HashMap::new()),
            withdrawal_plan_cache: Mutex::new(std::collections::VecDeque::new()),
        })
    }

    /// Insert a withdrawal plan into the cache, replacing any plan under the
    /// same id. Evicts the oldest plans once the cache holds more than 8.
    pub(crate) async fn cache_withdrawal_plan(
        &self,
        plan_id: String,
        plan: crate::sdk::bitcoin_tap_sdk::WithdrawalPlan,
        destination_address: String,
    ) {
        const MAX_CACHED_PLANS: usize = 8;
        let mut cache = self.withdrawal_plan_cache.lock().await;
        cache.retain(|(id, _)| *id != plan_id);
        cache.push_back((
            plan_id,
            CachedWithdrawalPlan {
                plan,
                destination_address,
            },
        ));
        while cache.len() > MAX_CACHED_PLANS {
            cache.pop_front();
        }
    }

    /// Take a cached plan by plan_id (removes it from the cache).
    pub(crate) async fn take_cached_withdrawal_plan(
        &self,
        plan_id: &str,
    ) -> Option<CachedWithdrawalPlan> {
        let mut cache = self.withdrawal_plan_cache.lock().await;
        let at = cache.iter().position(|(id, _)| id == plan_id)?;
        cache.remove(at).map(|(_, cached)| cached)
    }

    pub(crate) fn ensure_authoritative_wallet_state(
        &self,
        caller: &str,
    ) -> Result<dsm::types::state_types::State, dsm::types::error::DsmError> {
        let state = match self.core_sdk.get_current_state() {
            Ok(state) => state,
            Err(e) => {
                log::info!(
                    "[{caller}] no in-memory canonical state; attempting cold-start archive restore: {e}"
                );
                self.core_sdk.restore_latest_archived_state_for_device()?;
                self.core_sdk.get_current_state()?
            }
        };
        self.wallet.project_balance_cache_for_self(&state)?;
        Ok(state)
    }

    fn classify_local_state_update_failure(
        &self,
        error: &dsm::types::error::DsmError,
    ) -> &'static str {
        let message = error.to_string();
        if message.contains("Invalid operation: Insufficient balance for transfer")
            || message.contains("Insufficient balance for transfer")
        {
            "sdk_cache_update_insufficient_balance"
        } else if message.contains("Insufficient balance for token") {
            "core_canonical_insufficient_balance"
        } else {
            "other"
        }
    }

    // Helper: Shared logic for OnlineTransferRequest processing
    pub(crate) async fn process_online_transfer_logic(
        &self,
        transfer_req: generated::OnlineTransferRequest,
    ) -> AppResult {
        // Check network connectivity before attempting online transfer
        // Validate required fields for canonical signing (AF-2 remediation)
        if transfer_req.from_device_id.len() != 32 {
            return err("wallet.send: from_device_id must be 32 bytes".into());
        }
        if transfer_req.to_device_id.len() != 32 {
            return err("wallet.send: to_device_id must be 32 bytes".into());
        }

        // Resolve device IDs first — needed to derive the bilateral chain tip below.
        let Ok(from_device_id) = <[u8; 32]>::try_from(transfer_req.from_device_id.as_slice())
        else {
            return err("wallet.send: from_device_id must be 32 bytes".into());
        };
        let Ok(to_device_id) = <[u8; 32]>::try_from(transfer_req.to_device_id.as_slice()) else {
            return err("wallet.send: to_device_id must be 32 bytes".into());
        };
        let to_device_id_str = crate::util::text_id::encode_base32_crockford(&to_device_id);
        // The network's pinned set: the recipient's directory entry is read
        // there, and the send is delivered there.
        let network = match crate::sdk::economic_admission_flow::committed_network_id() {
            Ok(network) => network,
            Err(e) => return err(format!("wallet.send: no committed network: {e}")),
        };
        let spool_set = match crate::sdk::storage_set::canonical_set(&network) {
            Ok(set) => set,
            Err(e) => return err(format!("wallet.send: no pinned storage set: {e}")),
        };
        let storage_endpoints: Vec<String> = spool_set
            .members()
            .iter()
            .map(|member| member.endpoint.clone())
            .collect();

        // §4 (spec): h_n is the BILATERAL RELATIONSHIP tip for (self ↔ recipient).
        // This value is owned entirely by the SDK and persisted in contacts.chain_tip;
        // no request carries it.
        // When a stored tip is missing, restore the canonical initial relationship tip
        // derived from both devices' genesis/device identities instead of inventing a
        // zero-tip route.
        let local_genesis_for_routing: [u8; 32] = match self
            .core_sdk
            .local_genesis_hash()
            .await
            .ok()
            .and_then(|v| v.as_slice().try_into().ok())
        {
            Some(genesis) => genesis,
            None => {
                return err(
                    "wallet.send: local genesis unavailable for canonical relationship routing"
                        .to_string(),
                )
            }
        };
        let contact_record =
            match crate::storage::client_db::get_contact_by_device_id(&to_device_id) {
                Ok(Some(contact)) => contact,
                Ok(None) => {
                    return err(
                        "wallet.send: recipient must be an added contact before online send"
                            .to_string(),
                    )
                }
                Err(e) => {
                    return err(format!(
                        "wallet.send: failed to load recipient contact: {e}"
                    ))
                }
            };
        // The recipient's own directory entry: the AK pinned at pairing must be
        // the one it proves, and the Kyber key it signs is what the send seals
        // for.
        let Ok(recipient_genesis) = <[u8; 32]>::try_from(contact_record.genesis_hash.as_slice())
        else {
            return err("wallet.send: the recipient contact's genesis is not 32 bytes".into());
        };
        match crate::sdk::device_directory::read_entry(
            &spool_set,
            &recipient_genesis,
            &to_device_id,
        )
        .await
        {
            Ok(Some(read)) => {
                if let Err(e) = self
                    .repair_contact_identity_from_directory(contact_record, &read.entry)
                    .await
                {
                    return err(format!("wallet.send: {e}"));
                }
            }
            Ok(None) => {
                return err(
                    "wallet.send: no directory entry of the recipient proves itself on the set \
                     yet"
                    .into(),
                )
            }
            Err(e) => {
                return err(format!(
                    "wallet.send: the recipient's directory entry could not be read ({e})"
                ));
            }
        }
        let preflight_sync = generated::StorageSyncRequest {
            pull_inbox: true,
            push_pending: true,
            limit: 50,
        };
        match self.run_storage_sync_request(preflight_sync).await {
            Ok(resp) => {
                if !resp.errors.is_empty() {
                    log::warn!(
                        "wallet.send: preflight storage.sync completed with {} error(s): {:?}",
                        resp.errors.len(),
                        resp.errors
                    );
                }
            }
            Err(e) => {
                return err(format!(
                    "wallet.send: failed to refresh relationship state before send: {e}"
                ));
            }
        }
        let contact_record =
            match crate::storage::client_db::get_contact_by_device_id(&to_device_id) {
                Ok(Some(contact)) => contact,
                Ok(None) => {
                    return err(
                        "wallet.send: recipient relationship disappeared during send".to_string(),
                    )
                }
                Err(e) => {
                    return err(format!(
                        "wallet.send: failed to reload recipient relationship state: {e}"
                    ))
                }
            };

        let chain_tip_arr: [u8; 32] = match relationship_tip_for_contact_restore(
            self.device_id_bytes,
            local_genesis_for_routing,
            &contact_record,
        ) {
            Some(tip) => tip,
            None => {
                return err(
                    "wallet.send: recipient relationship tip is unavailable or invalid".to_string(),
                )
            }
        };

        // =====================================================================
        // DIAGNOSTIC: Check if to_device_id matches any contact's chain_tip
        // This guards against the bug where UI passes chain_tip as device_id
        // =====================================================================
        log::info!(
            "[wallet.send] 🔍 to_device_id first8={:02x}{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}{:02x} chain_tip first8={:02x}{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}",
            to_device_id[0], to_device_id[1], to_device_id[2], to_device_id[3],
            to_device_id[4], to_device_id[5], to_device_id[6], to_device_id[7],
            chain_tip_arr[0], chain_tip_arr[1], chain_tip_arr[2], chain_tip_arr[3],
            chain_tip_arr[4], chain_tip_arr[5], chain_tip_arr[6], chain_tip_arr[7],
        );

        // GUARDRAIL: Detect if to_device_id == chain_tip (indicates UI passed wrong field)
        if to_device_id == chain_tip_arr && chain_tip_arr != [0u8; 32] {
            log::error!(
                "[wallet.send] ❌ CRITICAL BUG: to_device_id == chain_tip! Frontend is passing chain_tip as recipient. First8={}",
                dsm::core::utility::labeling::hash_to_short_id(&to_device_id)
            );
            return err("wallet.send: to_device_id matches chain_tip - UI bug detected. Must use recipient's device_id, not chain_tip.".into());
        }

        log::info!(
            "[wallet.send] 📋 Contact {} found: canonical_relationship_tip={}",
            contact_record.alias,
            dsm::core::utility::labeling::hash_to_short_id(&chain_tip_arr)
        );

        // CERT-RESYNC GATE (fail-closed). A relationship whose per-step-EK cert
        // chain was lost must NOT fall back to the root AK — the peer chains
        // against its stored head and would reject us, and silently root-AK
        // sending is exactly the recovery-disguised-as-transfer the resync
        // protocol forbids. Ordinary sending stays blocked until an explicit
        // jointly-authorized resync finalizes.
        let resync_rel_key = dsm::core::bilateral_transaction_manager::compute_smt_key(
            &from_device_id,
            &to_device_id,
        );
        // Detect head-loss on an ESTABLISHED relationship. The Local cert head
        // is lost when there is none, no pending one either — a sent step not
        // yet finalized holds its head pending, which is in flight, not lost —
        // and THIS device sent on the relationship before. A receive-
        // established relationship's first send has no prior proposal: the
        // normal root-AK genesis bootstrap, allowed through. Any of these
        // reads failing fails the send closed.
        let local_head_present = match crate::storage::client_db::load_cert_chain_head_pubkey(
            &resync_rel_key,
            crate::storage::client_db::CertChainSide::Local,
        ) {
            Ok(head) => head.is_some(),
            Err(e) => return err(format!("wallet.send: cert-chain head read failed: {e}")),
        };
        let pending_head_present =
            match crate::storage::client_db::pending_local_head_exists(&resync_rel_key) {
                Ok(present) => present,
                Err(e) => return err(format!("wallet.send: pending cert-head read failed: {e}")),
            };
        let had_prior_send =
            match crate::storage::client_db::relationship_had_prior_send(&resync_rel_key) {
                Ok(sent) => sent,
                Err(e) => return err(format!("wallet.send: prior-send read failed: {e}")),
            };
        if !local_head_present && !pending_head_present && had_prior_send {
            if let Err(e) = crate::storage::client_db::mark_cert_resync_required(&resync_rel_key) {
                return err(format!(
                    "wallet.send: the lost cert-chain head could not be recorded: {e}"
                ));
            }
        }
        match crate::storage::client_db::cert_resync_blocks_send(&resync_rel_key) {
            Ok(true) => {
                return err(
                    "wallet.send: this relationship needs a cert-chain resync before sending \
                     (per-step-EK head was lost); an ordinary send is blocked until the \
                     jointly-authorized resync finalizes"
                        .to_string(),
                )
            }
            Ok(false) => {}
            Err(e) => {
                // Fail closed: if we cannot read the resync state, do not send.
                return err(format!("wallet.send: cert-resync gate check failed: {e}"));
            }
        }

        // A transfer names its token exactly; an omitted token is not ERA, and a
        // ticker is not case-folded into one it does not spell.
        let token_id = transfer_req.token_id.clone();
        if token_id.is_empty() {
            return err("wallet.send: the request names no token".to_string());
        }
        if contact_record.public_key.is_empty() {
            return err(
                "wallet.send: recipient contact is missing a canonical public key".to_string(),
            );
        }
        let recipient_owner = contact_record.public_key.clone();

        // §4.1: Nonce = "fresh entropy e" — generated deterministically by the SDK.
        // Formula: BLAKE3("DSM/nonce\0" || h_n || amount || token_id || recipient)
        // transfer_req.nonce from the frontend is ignored (reserved/ignored per proto comment).
        // The nonce is embedded in the Operation payload and transmitted to the receiver via the
        // b0x envelope, so both sides use identical bytes for compute_precommit. Clockless: no
        // wall-clock, no OS randomness, no counter — h_n is the per-relationship bilateral chain
        // tip, unique per relationship step, and the payload separates transfers at one step.
        let nonce: Vec<u8> = {
            let mut hasher =
                dsm::crypto::blake3::dsm_domain_hasher(dsm::common::domain_tags::TAG_DSM_NONCE);
            // h_n: bilateral chain tip — unique per relationship step
            hasher.update(&chain_tip_arr);
            // payload binding: amount + token_id + recipient — prevents cross-transfer reuse
            hasher.update(&transfer_req.amount.to_le_bytes());
            hasher.update(token_id.as_bytes());
            hasher.update(&to_device_id);
            hasher.finalize().as_bytes().to_vec()
        };
        // =====================================================================
        // CANONICAL SIGNATURE GENERATION
        // Sign the canonical Operation bytes (signature field cleared) so the
        // state machine and inbox verifier use the same preimage.
        // =====================================================================
        // §9.5: bind the token's canonical policy_commit into the signed transfer.
        // Resolve from the local source-of-truth installed policy; fail closed if
        // the token's policy is not installed (no peer-supplied fallback).
        let policy_commit = match self
            .core_sdk
            .resolve_policy_commit_strict(token_id.as_bytes())
        {
            Ok(pc) => pc,
            Err(e) => return err(format!("wallet.send: policy_commit resolve failed: {e}")),
        };
        let signing_op = dsm::types::operations::Operation::Transfer {
            to_device_id: to_device_id.to_vec(),
            amount: dsm::types::token_types::Balance::amount(transfer_req.amount),
            token_id: token_id.as_bytes().to_vec(),
            policy_commit,
            mode: dsm::types::operations::TransactionMode::Unilateral,
            nonce: nonce.clone(),
            verification: dsm::types::operations::VerificationType::Standard,
            pre_commit: None,
            recipient: recipient_owner.clone(),
            to: to_device_id_str.as_bytes().to_vec(),
            message: transfer_req.memo.clone(),
            signature: Vec::new(),
            authority_policy: None,
        };
        let signing_bytes = signing_op.to_bytes();

        // Diagnostic: log preimage hash for debugging sender/receiver mismatch
        let preimage_hash = dsm::crypto::blake3::domain_hash(
            dsm::common::domain_tags::TAG_DSM_SIGNING_PREIMAGE,
            &signing_bytes,
        );
        log::info!(
            "🔐 wallet.send: canonical signing preimage hash(first8)={:?} amount={} token={}",
            &preimage_hash.as_bytes()[..8],
            transfer_req.amount,
            token_id
        );

        // Sign with device's SPHINCS+ key
        let canonical_signature = match self.wallet.sign_operation_bytes(&signing_bytes) {
            Ok(sig) => {
                log::info!(
                    "[wallet.send] ✅ Canonical signature generated (len={})",
                    sig.len()
                );
                sig
            }
            Err(e) => return err(format!("wallet.send: canonical signing failed: {e}")),
        };

        // §4.3#1 Defensive: Sender self-verifies signature after signing.
        // Catches silent signing failures before propagating to receiver.
        // MUST use signing_authority public key — the same keypair that produced
        // the signature — NOT core_sdk state which may hold a different key.
        {
            let sender_pk = match crate::sdk::signing_authority::current_public_key() {
                Ok(pk) => pk,
                Err(e) => {
                    return err(format!(
                        "wallet.send: cannot retrieve signing authority public key for self-verify: {e}"
                    ));
                }
            };
            match dsm::crypto::sphincs::sphincs_verify(
                &sender_pk,
                &signing_bytes,
                &canonical_signature,
            ) {
                Ok(true) => {
                    log::info!("[wallet.send] §4.3#1 Sender self-verify: signature OK");
                }
                Ok(false) => {
                    return err(
                        "wallet.send: SPHINCS+ self-verification FAILED — signature is invalid, aborting"
                            .to_string(),
                    );
                }
                Err(e) => {
                    return err(format!(
                        "wallet.send: SPHINCS+ self-verification error: {e}"
                    ));
                }
            }
        }

        // For online transfers, ensure recipient is in device book
        let recipient_in_book = match self.wallet.get_device_book() {
            Ok(book) => book.contains_key(&to_device_id_str),
            Err(_) => false,
        };
        if !recipient_in_book {
            if let Err(e) = self.wallet.add_device_book_entry(
                &to_device_id_str,
                vec![],
                &format!("online-{}", &to_device_id_str[..8]),
            ) {
                return err(format!("Failed to add recipient to device book: {e}"));
            }
        }

        // Ensure bilateral chain is initialized for this counterparty (first send)
        let to_device_id_bytes =
            match crate::util::text_id::decode_base32_crockford(&to_device_id_str) {
                Some(bytes) => bytes,
                None => return err(format!("Invalid base32 device ID: {}", to_device_id_str)),
            };
        if to_device_id_bytes.len() != 32 {
            return err(format!(
                "Device ID must decode to 32 bytes, got {}",
                to_device_id_bytes.len()
            ));
        }

        if self
            .wallet
            .get_bilateral_chain_tip(&to_device_id_bytes)
            .is_err()
        {
            let initial_state_hash =
                match crate::storage::client_db::get_contact_by_device_id(&to_device_id) {
                    Ok(Some(contact)) => contact
                        .current_chain_tip
                        .as_ref()
                        .map(|h| crate::util::text_id::encode_base32_crockford(h))
                        .unwrap_or_else(|| "".to_string()),
                    _ => "".to_string(),
                };

            let initial_state_hash_bytes = if initial_state_hash.is_empty() {
                vec![]
            } else {
                match crate::util::text_id::decode_base32_crockford(&initial_state_hash) {
                    Some(bytes) => bytes,
                    None => {
                        return err(format!(
                            "Invalid base32 initial state hash: {}",
                            initial_state_hash
                        ))
                    }
                }
            };
            if !initial_state_hash_bytes.is_empty() && initial_state_hash_bytes.len() != 32 {
                return err(format!(
                    "Initial state hash must decode to 32 bytes or be empty, got {}",
                    initial_state_hash_bytes.len()
                ));
            }

            if let Err(e) = self
                .wallet
                .initialize_bilateral_chain(&to_device_id_str, &initial_state_hash_bytes)
            {
                return err(format!(
                    "Failed to initialize bilateral chain for recipient: {e}"
                ));
            }
        }

        // Pure function of the two device ids; hoisted because the transfer id now
        // binds to it (identity v2).
        let smt_key = dsm::core::bilateral_transaction_manager::compute_smt_key(
            &from_device_id,
            &to_device_id,
        );

        // Create the local transaction record (needed for metadata/bilateral tip updates)
        let unsigned_tx = match self
            .wallet
            .create_transaction(
                &to_device_id_str,
                transfer_req.amount,
                Some(&token_id),
                Some(&transfer_req.memo),
                None, // fee
                // Identity v2: bind the transfer id to the relationship and the
                // operation nonce, so two same-amount sends can no longer share an
                // id merely by landing in the same commit height.
                Some(&smt_key),
                Some(nonce.as_slice()),
            )
            .await
        {
            Ok(tx) => tx,
            Err(e) => return err(format!("create_transaction failed: {e}")),
        };

        // Sign the WalletTransaction (local wallet-level signature for record keeping)
        let signed_tx = match self.wallet.sign_transaction(&unsigned_tx) {
            Ok(tx) => tx,
            Err(e) => return err(format!("sign_transaction failed: {e}")),
        };

        // Build the final signed Operation from the SAME signing_op that was used for
        // canonical signature generation, so every verifier reads identical bytes.
        let signed_op = dsm::types::operations::Operation::Transfer {
            to_device_id: to_device_id.to_vec(),
            amount: dsm::types::token_types::Balance::amount(transfer_req.amount),
            token_id: token_id.as_bytes().to_vec(),
            policy_commit,
            mode: dsm::types::operations::TransactionMode::Unilateral,
            nonce: nonce.clone(),
            verification: dsm::types::operations::VerificationType::Standard,
            pre_commit: None,
            recipient: recipient_owner.clone(),
            to: to_device_id_str.as_bytes().to_vec(),
            message: transfer_req.memo.clone(),
            signature: canonical_signature.clone(),
            authority_policy: None,
        };

        // The pre-send head snapshot is gone: it existed ONLY to let the rollback
        // path revert `bcr_device_heads`, and the advance transaction now unwinds
        // that itself.
        //
        // This call is NOT dead with it. It is a fail-closed precondition that
        // also performs cold-start archive restore and projects the balance
        // cache; only its return value was rollback bookkeeping.
        if let Err(e) = self.ensure_authoritative_wallet_state("wallet.send") {
            return err(format!(
                "wallet.send: failed to prepare authoritative state before send: {e}"
            ));
        }

        // §5.4 Modal lock: reserve this (A,B) relationship before any local mutation.
        // If another online transition is already pending, fail closed.
        // Held for the rest of this function. Releasing it is the guard's job, on
        // EVERY exit — success, each early error return, and panic. It is
        // application state: the advance transaction does not unwind it, so it
        // must not be tangled up with the protocol rollbacks being removed here.
        let _modal_lock = match crate::security::modal_sync_lock::PendingOnlineGuard::acquire(
            &smt_key,
        ) {
            Some(guard) => guard,
            None => {
                return err(
                    "wallet.send: relationship already has a pending online transition; retry after sync"
                        .to_string(),
                )
            }
        };

        // FINALITY BARRIER — the send-ready AUTHORITY, consulted BEFORE any
        // mutation. The modal lock above is in-memory only. The durable
        // conditions are: our prior send on this relationship has not reached
        // its finality checkpoint (gate armed), or an inbound acceptance we
        // journaled still awaits the peer's certificate. Either way this device
        // may not originate — refusing here is what keeps a second-generation
        // transfer from being DELIVERED before its predecessor is final. This is
        // an ordinary PendingCatchup, not divergence: nothing is marked for
        // reconcile.
        let send_status =
            crate::handlers::relationship_status::derive_local_send_status_for_device_id(
                &to_device_id,
            );
        if !send_status.send_ready {
            return err(format!(
                "wallet.send: relationship is not send-ready: {}",
                crate::handlers::relationship_status::status_message(&send_status)
            ));
        }

        // Tripwire preflight: the parent tip may be consumed only once.
        match crate::storage::client_db::contact_chain_tip_matches_expected(
            &to_device_id,
            &chain_tip_arr,
        ) {
            Ok(true) => {}
            Ok(false) => {
                let marked =
                    crate::storage::client_db::mark_contact_needs_online_reconcile(&to_device_id)
                        .err()
                        .map(|e| format!("; marking the contact for reconciliation failed: {e}"))
                        .unwrap_or_default();
                return err(format!(
                    "wallet.send: ParentConsumed - relationship tip changed before send; online \
                     reconciliation required{marked}"
                ));
            }
            Err(e) => {
                return err(format!(
                    "wallet.send: failed to validate relationship parent tip: {e}"
                ));
            }
        }

        // ── 3.5b SENDER ECONOMIC ADMISSION (register at send) ──────────────
        // A pending admission is RESUMED first — never abandoned, never raced
        // (the authoritative serialization is inside the advance seam; this
        // early pass keeps the deep-fence refusal from being the first line
        // of defense). Then the prerequisites for THIS send's admission are
        // assembled: the debit registers before anything is deliverable.
        let econ_network = match crate::sdk::economic_admission_flow::committed_network_id() {
            Ok(n) => n,
            Err(e) => return err(format!("wallet.send: committed network: {e}")),
        };
        {
            let pending = self
                .core_sdk
                .device_head()
                .and_then(|h| h.pending_economic_admission().cloned());
            if let Some(pending) = pending {
                if let Err(e) = crate::sdk::economic_admission_flow::resume_pending_admission(
                    &self.core_sdk,
                    &econ_network,
                    pending,
                )
                .await
                {
                    return err(format!(
                        "wallet.send: a pending economic admission could not be finished — \
                         retry once storage is reachable: {e}"
                    ));
                }
            }
        }
        let econ_set = match crate::sdk::storage_set::canonical_set(&econ_network) {
            Ok(s) => s,
            Err(e) => return err(format!("wallet.send: canonical register set: {e}")),
        };
        let econ_validated =
            match crate::sdk::economic_admission_flow::validated_root_or_activate(&self.core_sdk) {
                Ok(v) => v,
                Err(e) => return err(format!("wallet.send: economic root: {e}")),
            };
        let (econ_genesis, econ_devid) = match self.core_sdk.device_head() {
            Some(h) => (h.genesis_digest(), h.devid()),
            None => return err("wallet.send: no device head".to_string()),
        };
        // Pre-balances come from R_econ ITSELF, never the head snapshot: the
        // head can hold credits no admission backs yet (a received transfer
        // awaiting recipient admission), and a debit built on those would
        // pair a pre-state the validated pre-root cannot prove.
        let (econ_tree, econ_pre_state) =
            match crate::sdk::economic_admission_flow::producer_tree_and_pre_state(&econ_validated)
            {
                Ok((t, b)) => (std::cell::RefCell::new(t), b),
                Err(e) => return err(format!("wallet.send: economic tree: {e}")),
            };
        let econ_authority = match crate::sdk::economic_admission_flow::authority_material(
            &econ_network,
            &econ_genesis,
        ) {
            Ok(a) => a,
            Err(e) => return err(format!("wallet.send: authority evidence: {e}")),
        };
        let econ_target_position = econ_validated.economic_position() + 1;
        let admission_op = signed_op.clone();
        let admission_op_digest =
            dsm::economic::admission::dsm_operation_digest(&admission_op.to_bytes());
        let econ_pre_root = econ_tree.borrow().root();
        let econ_prepared = dsm::economic::admission::PendingEconomicAdmission::prepared(
            dsm::economic::admission::PendingAdmissionKind::DsmBacked,
            econ_target_position,
            econ_pre_root,
            admission_op_digest,
        );
        let admission_parts: std::cell::RefCell<
            Option<crate::sdk::economic_admission_flow::DsmAdmissionParts>,
        > = std::cell::RefCell::new(None);
        let mut accepted_admission: Option<dsm::economic::admission::PendingEconomicAdmission> =
            None;

        // §16.6 CRITICAL: Use UNSIGNED canonical bytes for tip computation.
        // signed_op.to_bytes() includes the SPHINCS+ signature, which the receiver cannot
        // know at σ-derivation time. signing_bytes was built from signing_op with
        // signature: Vec::new() — the same unsigned preimage used by the receiver when it
        // calls compute_precommit on the cleared operation. Both sides now hash identical bytes.
        let op_bytes_for_tip = signing_bytes.clone();

        // Execute local state update using the pre-built signed Operation directly.
        // This bypasses execute_signed_transfer which would reconstruct a different
        // Operation (empty nonce, different Balance) causing signature verification failure.
        // Returns the display State view plus the AdvanceOutcome whose smt_proofs
        // / parent_r_a / child_r_a drive the canonical ReceiptCommit build below.

        // Canonical C_pre and the symmetric h_{n+1} take the ONE transition
        // entropy — Core's derivation inside the prepared advance (Part VII
        // step 3, §39.3) — over h_n and the payload bytes. They are therefore
        // computed inside `build_online_send_artifacts`, from the outcome, not
        // here: nothing exists to hash before Core has prepared the step. The
        // transfer nonce stays in the operation bytes (§39.4). The receiver
        // reads the entropy off the signed receipt (canonical field 21) and
        // recomputes both hashes.
        let op_bytes = op_bytes_for_tip;

        // ReceiptCommit built directly from the AdvanceOutcome produced by the
        // canonical §2.2 Per-Device SMT advance (no shadow SMT replace).
        // Inclusion proofs verify against the A-side (asymmetric) chain tip
        // that now sits in DeviceState.smt — symmetric `new_chain_tip` is
        // still used downstream for contacts.chain_tip + b0x addressing.
        //
        // `parent_r_a` is the CAS-layer head entering the advance. On a
        // first-ever relationship advance, the internal seed step changes the
        // Merkle preimage before `smt_replace`, so the parent proof verifies
        // against `smt_proofs.pre_root`, not `parent_r_a`.
        // §16.6 defect zero: EK material captured during signing, written later
        // inside the single pre-submit transaction (see PendingEkMaterial).
        // =====================================================================
        // GAP 1 — STAGED PAYLOAD.
        //
        // Everything the send must decide BEFORE anything is deliverable now runs
        // inside `build_online_send_artifacts`: receipt construction and
        // self-verification, per-step EK signing, final envelope construction, and
        // the proposal / gate / pending-head / outbox material.
        //
        // It runs AFTER the pure `prepare_advance_relationship` and BEFORE the
        // durable write, so a failure here has nothing to unwind — that is why all
        // 18 rollback branches below collapsed into plain `Err`. The canonical
        // advance and this whole bundle then commit in ONE transaction, so the
        // debit can never exist without its lifecycle record.
        //
        // DEADLOCK: this closure runs while `core_sdk`'s `state_machine`
        // parking_lot mutex is HELD and that mutex is NOT reentrant. Nothing here
        // may call into `CoreSDK` — a re-lock hangs silently, with no panic and no
        // error. DB reads are fine: the connection mutex is taken later.
        // =====================================================================
        let build_online_send_artifacts = |advance_outcome: &dsm::types::device_state::AdvanceOutcome|
         -> Result<OnlineSendArtifacts, dsm::types::error::DsmError> {
            let transition_entropy = advance_outcome.transition_entropy();
            let receipt_sigma = dsm::core::bilateral_transaction_manager::compute_precommit(
                &chain_tip_arr,
                &op_bytes,
                &transition_entropy,
            );
            let new_chain_tip = dsm::core::bilateral_transaction_manager::compute_successor_tip(
                &chain_tip_arr,
                &op_bytes,
                &transition_entropy,
                &receipt_sigma,
            );
            // The economic admission is built FIRST, from the exact prepared
            // successor — the wire locators below are OUTPUTS of this build
            // (correction C), never predictions beside it.
            let econ_parts = crate::sdk::economic_admission_flow::build_dsm_admission(
                &econ_genesis,
                &econ_devid,
                &advance_outcome.new_chain_state,
                &admission_op,
                &econ_pre_state,
                &mut econ_tree.borrow_mut(),
                &dsm::economic::write_set::CreditSourceFacts::None,
                &econ_authority,
                Vec::new(),
            )?;
            let econ_debit_index = econ_parts.debit_mutation_index.ok_or_else(|| {
                dsm::types::error::DsmError::invalid_operation(
                    "wallet.send: the sender write set has no debit mutation — refusing to \
                     freeze locators that name nothing",
                )
            })?;
            *admission_parts.borrow_mut() = Some(econ_parts);
            #[allow(unused_assignments)]
            let mut pending_ek_material: Option<PendingEkMaterial> = None;
            let (receipt_commit_bytes, receipt_canonical_bytes) = {
                // h_n / h_{n+1} asymmetric (A-side) values stored in T_A. The
                // advance's path carries h_n; a path without it proves nothing.
                let parent_tip_asymmetric =
                    advance_outcome.smt_proofs.parent_proof.value.ok_or_else(|| {
                        dsm::types::error::DsmError::invalid_operation(
                            "wallet.send: the advance's relationship path carries no parent tip",
                        )
                    })?;
                let child_tip_asymmetric = advance_outcome.new_chain_state.compute_chain_tip();
                let parent_root_for_receipt = advance_outcome.smt_proofs.pre_root;

                // Build ReceiptCommit with real SMT roots and proofs
                // Use local Device Tree root (R_G) for receipt construction
                let local_device_tree_commitment =
                    crate::sdk::app_state::AppState::get_device_tree_commitment().ok_or_else(
                        || {
                            dsm::types::error::DsmError::invalid_operation(
                                "wallet.send: this device holds no Device Tree commitment",
                            )
                        },
                    )?;
                let rc_canonical = crate::sdk::receipts::build_bilateral_receipt_with_smt(
                    from_device_id,
                    to_device_id,
                    parent_tip_asymmetric,
                    child_tip_asymmetric,
                    parent_root_for_receipt,
                    advance_outcome.child_r_a,
                    &advance_outcome.smt_proofs.parent_proof,
                    &local_device_tree_commitment,
                    advance_outcome.transition_entropy(),
                )?;

                // §4.2 + §11.1 Non-repudiation: Sender answers the receipt
                // challenge as sig_a using a freshly-derived per-step ephemeral
                // SPHINCS+ key (§11.1).
                // The cert chain anchors the per-step EK back to the device's AK_pk;
                // the receipt response is verified against the EK_pk_a carried in
                // the envelope (proto field 16). Verifiers don't need the wallet's
                // long-term identity key out-of-band — sig_a verifies against
                // receipt.ek_pk_a, which is authorized via receipt.ek_cert_a.
                //
                // The receipt challenge is signed by a per-step EK derived from
                // canonical C_pre and fresh Kyber k_step material (keyed under Smaster).
                let rc = match dsm::types::receipt_types::StitchedReceiptV2::from_canonical_protobuf(
                    &rc_canonical,
                ) {
                    Ok(mut receipt) => match receipt.compute_commitment() {
                        Ok(commitment) => {
                            // Resolve the chain-head at-rest key (s0-rooted, re-derived from the
                            // unlocked wallet; no C-DBRW) + root AK keypair. The per-step EK seed +
                            // ML-KEM coins re-derive Smaster inside `sign_receipt_with_per_step_ek`.
                            let at_rest_key = match crate::init::current_chain_head_at_rest_key() {
                                Ok(k) => k,
                                Err(e) => {
                                    return Err(dsm::types::error::DsmError::invalid_operation(format!(
                                        "wallet.send: chain-head key unavailable for cert chain (wallet locked?): {e}"
                                    )));
                                }
                            };
                            let (ak_pk, ak_sk) = match self.wallet.ak_keypair_for_cert_chain() {
                                Ok(kp) => kp,
                                Err(e) => {
                                    // The canonical advance has ALREADY happened at this
                                    // point, so bailing out without unwinding it would
                                    // strand a debit and leave the relationship's modal
                                    // lock held (blocking every later send). Every
                                    // neighbouring arm rolls back; this one used to just
                                    // return.
                                    return Err(dsm::types::error::DsmError::invalid_operation(format!(
                                        "wallet.send: AK keypair unavailable for cert chain: {e}"
                                    )));
                                }
                            };

                            // §16.6 defect zero: snapshot the committed Local cert head
                            // BEFORE signing. Signing must run outside the durable
                            // transaction (it reads cert heads through its own
                            // connection), so this snapshot is what the later CAS
                            // compares against to detect the acceptance finalizer moving
                            // the head underneath us.
                            //
                            // Compute relationship_key for chain head lookup.
                            let rel_key = dsm::core::bilateral_transaction_manager::compute_smt_key(
                                &receipt.devid_a,
                                &receipt.devid_b,
                            );
                            let local_head_before_signing =
                                crate::storage::client_db::load_cert_chain_head_pubkey(
                                    &rel_key,
                                    crate::storage::client_db::CertChainSide::Local,
                                )
                                .ok()
                                .flatten();

                            // Per-step Kyber per whitepaper §11: encapsulate
                            // against the recipient's Kyber pubkey to derive
                            // `k_step`. Pull the pubkey from the contact record;
                            // fail-closed if missing (no root path — contact
                            // must be re-established with peer Kyber pubkey to
                            // enable per-step EK signing).
                            let recipient_kyber_pk =
                                match crate::storage::client_db::get_contact_by_device_id(
                                    &receipt.devid_b,
                                ) {
                                    Ok(Some(c)) if !c.kyber_public_key.is_empty() => c.kyber_public_key,
                                    Ok(Some(_)) => {
                                        return Err(dsm::types::error::DsmError::invalid_operation(
                                        "wallet.send: recipient contact missing Kyber public key — \
                                         re-establish contact to upgrade for per-step EK signing\
                                         "
                    ));
                                    }
                                    _ => {
                                        return Err(dsm::types::error::DsmError::invalid_operation(
                                        "wallet.send: recipient contact lookup failed"
                    ));
                                    }
                                };

                            // Sign with per-step EK (whitepaper §11.1 cert chain).
                            let signing_inputs = crate::sdk::receipts::PerStepSigningInputs {
                                commitment: &commitment,
                                h_n: receipt.parent_tip,
                                c_pre: receipt_sigma,
                                devid_sender: receipt.devid_a,
                                relationship_key: rel_key,
                                root_ak_keypair: Some((&ak_pk, &ak_sk)),
                                recipient_kyber_pk: &recipient_kyber_pk,
                                // §11.1 Item 7: bind the per-step EK response
                                // to the receipt commitment for this online
                                // wallet.send transition.
                                session_binding: &commitment,
                            };
                            match crate::sdk::receipts::sign_receipt_with_per_step_ek(&signing_inputs) {
                                Ok(out) => {
                                    log::info!(
                                        "[wallet.send] §11.1 per-step EK sign: ek_pk_len={}, \
                                         cert_len={}, sig_len={}, used_root_ak={}",
                                        out.ek_pk.len(),
                                        out.ek_cert.len(),
                                        out.sig.len(),
                                        out.used_root_ak,
                                    );

                                    // Stamp per-step artifacts on the receipt.
                                    receipt.set_ek_pk_a(out.ek_pk.clone());
                                    receipt.set_ek_cert_a(out.ek_cert);
                                    receipt.set_kyber_ct_a(out.kyber_ct);
                                    receipt.add_sig_a(out.sig);

                                    // §11.1 lockstep: do NOT advance the committed Local
                                    // chain head at sign time. STASH the new EK head as
                                    // pending, keyed by this receipt commitment. It is
                                    // promoted into `cert_chain_heads` only once the
                                    // receiver's acceptance ACK is observed (storage.sync
                                    // sweep), and dropped if the transfer fails. This keeps
                                    // the sender's committed head unchanged for a transfer
                                    // that is never accepted, so a failed/timed-out attempt
                                    // cannot run the chain ahead of the receiver.
                                    // §16.6 defect zero: the pending head is NOT written
                                    // here. It is committed in ONE transaction with the
                                    // proposal, the gate, and the durable outbox row —
                                    // before anything is submitted — so a local failure can
                                    // never strand a deliverable message against a
                                    // rolled-back debit. Carry the material forward, plus
                                    // the pre-signing head snapshot that guards the CAS.
                                    pending_ek_material = Some(PendingEkMaterial {
                                        ek_pk: out.ek_pk.clone(),
                                        ek_sk: out.ek_sk.clone(),
                                        at_rest_key,
                                        is_init: out.used_root_ak,
                                        expected_prev: local_head_before_signing.clone(),
                                        is_first_ek_step: out.used_root_ak,
                                    });

                                    match receipt.to_full_protobuf() {
                                        Ok(full_bytes) => full_bytes,
                                        Err(e) => {
                                            return Err(dsm::types::error::DsmError::invalid_operation(format!(
                                                "wallet.send: receipt full serialization failed: {e}"
                                            )));
                                        }
                                    }
                                }
                                Err(e) => {
                                    return Err(dsm::types::error::DsmError::invalid_operation(format!(
                                        "wallet.send: per-step EK signing failed: {e}"
                                    )));
                                }
                            }
                        }
                        Err(e) => {
                            return Err(dsm::types::error::DsmError::invalid_operation(format!(
                                "wallet.send: receipt commitment hash failed: {e}"
                            )));
                        }
                    },
                    Err(e) => {
                        return Err(dsm::types::error::DsmError::invalid_operation(format!(
                            "wallet.send: receipt deserialization for signing failed: {e}"
                        )));
                    }
                };

                log::info!(
                    "[wallet.send] §4.2 canonical advance + receipt self-verified + sig_a embedded: smt_key={:?}.. pre_root={:?}.. post_root={:?}.. receipt_len={}",
                    &smt_key[..4],
                    &advance_outcome.parent_r_a[..4],
                    &advance_outcome.child_r_a[..4],
                    rc.len(),
                );
                (rc, rc_canonical)
            };

            // =====================================================================
            // §16.6 CANONICAL SENDER PROPOSAL (proposal authority) — ONE persisted
            // record written BEFORE any wire work. Its canonical pair comes from
            // the SIGNED artifact itself; its projection pair is the symmetric
            // routing lineage snapshotted at preparation. Every downstream
            // consumer (gate, wire entry, ACK finalization, rollback) reads THIS
            // record — `contacts.chain_tip` is never reread past this point.
            // =====================================================================
            let sender_proposal = {
                let parsed = match dsm::types::receipt_types::StitchedReceiptV2::from_canonical_protobuf(
                    &receipt_commit_bytes,
                ) {
                    Ok(r) => r,
                    Err(e) => {
                        return Err(dsm::types::error::DsmError::invalid_operation(format!(
                            "wallet.send: signed artifact reparse for proposal failed: {e}"
                        )));
                    }
                };
                let proposal_commitment = match parsed.compute_commitment() {
                    Ok(c) => c,
                    Err(e) => {
                        return Err(dsm::types::error::DsmError::invalid_operation(format!(
                            "wallet.send: proposal commitment failed: {e}"
                        )));
                    }
                };
                let operation_digest = {
                    let mut h =
                        dsm::crypto::blake3::dsm_domain_hasher(dsm::tagged_domain!(b"DSM/canonical-apply-op-digest/v1"));
                    h.update(&op_bytes);
                    let mut out32 = [0u8; 32];
                    out32.copy_from_slice(&h.finalize().as_bytes()[..32]);
                    out32
                };
                crate::storage::client_db::SenderOnlineProposal {
                    relationship_key: smt_key,
                    canonical_parent: parsed.parent_tip,
                    canonical_child: parsed.child_tip,
                    projection_parent: chain_tip_arr,
                    projection_target: new_chain_tip,
                    commitment: proposal_commitment,
                    operation_digest,
                    nonce_hash: crate::storage::codecs::hash_blake3_bytes(&nonce),
                    message_id: None,
                    tx_id: signed_tx.id.to_string(),
                    counterparty_device_id: to_device_id,
                    amount: transfer_req.amount,
                    token_id: token_id.clone(),
                    status: crate::storage::client_db::PROPOSAL_PROPOSED.to_string(),
                }
            };
            // =====================================================================
            // §16.6 DEFECT ZERO — ATOMIC PRE-SUBMIT COMMIT.
            //
            // Everything the transfer needs locally lands in ONE transaction BEFORE
            // a single byte goes to the network: proposal, pending online gate,
            // pending Local EK head (CAS'd against the pre-signing snapshot), and
            // the durable outbox row carrying the exact submission inputs.
            //
            // Failing here is safe and rolls back freely — nothing has been sent.
            // Succeeding here makes the transfer FORWARD-ONLY: from this point a
            // quorum may accept the message at any moment, so no later failure may
            // unwind the debit.
            // =====================================================================
            let ek_material = match pending_ek_material.take() {
                Some(m) => m,
                None => {
                    return Err(dsm::types::error::DsmError::invalid_operation(
                        "wallet.send: per-step EK material missing before durable commit"
                    ));
                }
            };

            let submission_id =
                crate::storage::client_db::derive_submission_id(&sender_proposal.commitment);

            let mut outbox_record = crate::storage::client_db::SenderOutboxRecord {
                relationship_key: sender_proposal.relationship_key,
                canonical_parent: sender_proposal.canonical_parent,
                proposal_nonce: sender_proposal.nonce_hash,
                canonical_child: sender_proposal.canonical_child,
                commitment: sender_proposal.commitment,
                projection_parent: sender_proposal.projection_parent,
                projection_target: sender_proposal.projection_target,
                routing_address: String::new(), // bound below, before submission
                submission_id: submission_id.clone(),
                envelope_bytes: Vec::new(), // bound below, before submission
                local_expected_prev: ek_material.expected_prev.clone(),
                is_first_ek_step: ek_material.is_first_ek_step,
                // HELD: the row is not deliverable until the admission
                // reaches ECON_ADMITTED, which promotes it atomically
                // (correction A). Neither the foreground path nor the sweep
                // can emit bytes for a held row.
                status: crate::storage::client_db::OUTBOX_ECONOMIC_ADMISSION_PENDING.to_string(),
                message_ids: None,
            };

            // =====================================================================
            // B0X SUBMISSION (deliver to recipient's inbox)
            // ATOMIC: If b0x fails, rollback the local balance deduction.
            // Use the CANONICAL signature so receiver verification succeeds.
            // =====================================================================
            // The empty-endpoints case is UNREACHABLE here: `fetch_quorum_device_identity`
            // rejects an empty endpoint list and this handler returns long before the
            // advance. The old `if !storage_endpoints.is_empty()` wrapper was therefore
            // dead, and — worse — it made the DURABLE COMMIT conditional. Flattened so
            // the commit is unconditional.
            log::info!("[wallet.send] Submitting to b0x with canonical signature");
            log::info!("[wallet.send] Submitting to b0x with canonical signature");

            // Build Operation for b0x submission
            let transfer_op = dsm::types::operations::Operation::Transfer {
                to_device_id: to_device_id.to_vec(),
                amount: dsm::types::token_types::Balance::amount(transfer_req.amount),
                token_id: token_id.as_bytes().to_vec(),
                policy_commit,
                mode: dsm::types::operations::TransactionMode::Unilateral,
                nonce: nonce.to_vec(),
                verification: dsm::types::operations::VerificationType::Standard,
                pre_commit: None,
                recipient: recipient_owner,
                to: to_device_id_str.as_bytes().to_vec(),
                message: transfer_req.memo.clone(),
                signature: canonical_signature.clone(),
                authority_policy: None,
            };

            // Reuse the genesis already resolved FAIL-CLOSED at the top of this
            // handler. Re-fetching here used to fall back to `vec![0u8; 32]`, which
            // would freeze an all-zero sender genesis into the durable envelope
            // bytes — unverifiable by the recipient and impossible to correct after
            // the outbox commits. It was also the last happy-path `.await` in the
            // block that must become a synchronous builder.
            let sender_genesis_b32 =
                crate::util::text_id::encode_base32_crockford(&local_genesis_for_routing);
            let sender_chain_tip_b32 =
                crate::util::text_id::encode_base32_crockford(&sender_proposal.projection_parent);
            // Use the signing authority's public key — derived from the same
            // (genesis_hash, device_id, binding_key) triple that produced the
            // secret key used for signing.  This is the ONLY correct source.
            let sender_signing_public_key = match crate::sdk::signing_authority::current_public_key(
            ) {
                Ok(pk) => pk,
                Err(e) => {
                    return Err(dsm::types::error::DsmError::invalid_operation(format!(
                            "wallet.send: cannot retrieve signing authority public key: {e}"
                        )));
                }
            };

            // Recipient genesis hash comes from the primed contact record that also
            // defines the canonical relationship tip used for routing.
            let recipient_genesis_raw: [u8; 32] = match contact_record
                .genesis_hash
                .as_slice()
                .try_into()
            {
                Ok(genesis) => genesis,
                Err(_) => {
                    return Err(dsm::types::error::DsmError::invalid_operation(
                        "wallet.send: recipient contact has invalid genesis hash for rotated b0x routing"
                    ));
                }
            };
            let recipient_genesis_b32 =
                crate::util::text_id::encode_base32_crockford(&recipient_genesis_raw);
            // Retained for the evidence artifact: `recipient_genesis_b32` is moved
            // into the transfer params below.
            let recipient_genesis_b32_for_evidence = recipient_genesis_b32.clone();

            // §16.4: Compute the tip-scoped b0x routing address.
            // The address is a single base32(32) digest over domain-separated
            // genesis/device/tip components, and the recipient derives the same
            // routing key during storage.sync polling.
            if recipient_genesis_raw == [0u8; 32] {
                return Err(dsm::types::error::DsmError::invalid_operation(
                    "wallet.send: recipient genesis is required for rotated b0x routing"
                    ));
            }

            // DIAGNOSTIC: Log the exact inputs used for b0x address computation so
            // receiver-side inbox.pull logs can be compared for address mismatch debugging.
            log::info!(
                "[wallet.send] §16.4 b0x address inputs: recipient_genesis={}.. recipient_device={}.. chain_tip={}.. (tip_is_zero={})",
                crate::util::text_id::encode_base32_crockford(&recipient_genesis_raw).get(..8).unwrap_or("?"),
                crate::util::text_id::encode_base32_crockford(&to_device_id).get(..8).unwrap_or("?"),
                crate::util::text_id::encode_base32_crockford(&chain_tip_arr).get(..8).unwrap_or("?"),
                chain_tip_arr == [0u8; 32],
            );

            let routing_address = match crate::sdk::b0x_sdk::B0xSDK::compute_b0x_address(
                &recipient_genesis_raw,
                &to_device_id,
                &chain_tip_arr,
            ) {
                Ok(addr) => {
                    log::info!(
                        "[wallet.send] §16.4 Computed rotated b0x routing address: {}",
                        &addr[..16.min(addr.len())]
                    );
                    addr
                }
                Err(e) => {
                    return Err(dsm::types::error::DsmError::invalid_operation(format!(
                        "wallet.send: b0x address rotation failed: {e}"
                    )));
                }
            };

            // ADR 0003: content address of the A-side evidence artifact, over the
            // EXACT wire bytes the receiver will verify signatures against --
            // never `compute_commitment()`, which hard-zeroes fields 12-20 and
            // would let a substituted-signature object satisfy the reference.
            let evidence_digest = crate::storage::client_db::evidence_content_digest(
                crate::storage::client_db::ArtifactRole::EvidenceA,
                &receipt_commit_bytes,
            );

            let b0x_params = crate::sdk::b0x_sdk::B0xSubmissionParams {
                // Deterministic, derived from the receipt commitment: known
                // before the local commit and identical on every retry, so a
                // resend collapses onto the same node spool row.
                submission_id: Some(submission_id.clone()),
                recipient_device_id: to_device_id_str.clone(),
                recipient_genesis_hash: recipient_genesis_b32,
                transaction: transfer_op,
                signature: canonical_signature.clone(),
                sender_genesis_hash: sender_genesis_b32,
                sender_chain_tip: sender_chain_tip_b32,
                sender_signing_public_key,
                // ADR 0003: the transfer no longer carries the receipt inline.
                // It carries a 32-byte role-separated reference to the evidence
                // artifact, which travels separately. Field 10 stays empty --
                // the two forms are different semantic types and must not share
                // a field.
                receipt_evidence_digest: evidence_digest.to_vec(),
                routing_address: routing_address.clone(),
                canonical_operation_bytes: signing_bytes.clone(),
                // OUTPUTS of the built admission (correction C).
                sender_economic_position: econ_target_position,
                sender_debit_mutation_index: econ_debit_index,
            };

            // ============================================================
            // §16.6 DEFECT ZERO — DURABILITY BEFORE DELIVERABILITY.
            //
            // The submission inputs are now fully determined, so freeze them
            // into the outbox row and commit proposal + gate + pending EK head
            // + outbox in ONE transaction. Only after this returns Ok may a
            // network call happen.
            //
            // A failure here is free: nothing has been sent, so the normal
            // rollback applies. After it succeeds, rollback is FORBIDDEN.
            // ============================================================
            outbox_record.routing_address = routing_address.clone();

            // Build the FINAL canonical envelope (no transmission) so the exact
            // wire bytes — not a recipe for rebuilding them — are what gets
            // frozen durably. A later retry replays these verbatim, so retry
            // identity survives any future change to envelope construction.
            let sender_b32_for_build =
                crate::util::text_id::encode_base32_crockford(&from_device_id);
            let evidence_builder = match crate::sdk::b0x_sdk::B0xSDK::new(
                sender_b32_for_build,
                self.core_sdk.clone(),
                storage_endpoints.clone(),
            ) {
                Ok(b) => b,
                Err(e) => {
                    return Err(dsm::types::error::DsmError::invalid_operation(format!(
                        "wallet.send: envelope builder init failed (nothing sent): {e}"
                    )));
                }
            };

            // ADR 0003 construction order, deliberately rigid:
            //   full_receipt_bytes -> digest -> evidence id
            //     -> TransferEnvelope(field10="", field12=digest)
            //     -> ReceiptEvidenceEnvelope(full bytes, digest)
            //     -> freeze BOTH exact encodings
            //     -> one 2a transaction persists both or neither
            // The persistence layer receives FINAL byte vectors, never anything
            // it could re-encode later: a rebuild is how a retry stops being the
            // same logical send.
            let (envelope_bytes, ..) =
                match evidence_builder.build_envelope_bytes(&b0x_params) {
                    Ok(pair) => pair,
                    Err(e) => {
                        return Err(dsm::types::error::DsmError::invalid_operation(format!(
                            "wallet.send: envelope build failed (nothing sent): {e}"
                        )));
                    }
                };
            // DSM Amendment A7: each spool payload is sealed for the recipient
            // once, here, before it is frozen; delivery submits the kept seal.
            if let Err(e) =
                crate::sdk::b0x_sdk::seal_for(&to_device_id, &submission_id, &envelope_bytes)
            {
                return Err(dsm::types::error::DsmError::invalid_operation(format!(
                    "wallet.send: sealing the transfer failed (nothing sent): {e}"
                )));
            }
            outbox_record.envelope_bytes = envelope_bytes.clone();

            let evidence_submission_id =
                crate::storage::client_db::derive_artifact_submission_id(&evidence_digest);
            let evidence_envelope = match evidence_builder.build_evidence_envelope(
                &to_device_id_str,
                &recipient_genesis_b32_for_evidence,
                &submission_id,
                &evidence_submission_id,
                &evidence_digest,
                &receipt_commit_bytes,
            ) {
                Ok(built) => built,
                Err(e) => {
                    return Err(dsm::types::error::DsmError::invalid_operation(format!(
                        "wallet.send: evidence envelope build failed (nothing sent): {e}"
                    )));
                }
            };

            if let Err(e) = crate::sdk::b0x_sdk::seal_for(
                &to_device_id,
                &evidence_submission_id,
                &evidence_envelope.bytes,
            ) {
                return Err(dsm::types::error::DsmError::invalid_operation(format!(
                    "wallet.send: sealing the evidence failed (nothing sent): {e}"
                )));
            }
            let evidence_artifact = crate::storage::client_db::SenderOutboxArtifact {
                relationship_key: sender_proposal.relationship_key,
                canonical_parent: sender_proposal.canonical_parent,
                proposal_nonce: sender_proposal.nonce_hash,
                role: crate::storage::client_db::ArtifactRole::EvidenceA,
                submission_id: evidence_submission_id,
                envelope_bytes: evidence_envelope.bytes,
                content_digest: evidence_digest,
                routing_address: None,
            };

            Ok(OnlineSendArtifacts {
                sender_proposal,
                outbox_record,
                submission_id,
                ek_material,
                receipt_canonical_bytes,
                extra_artifacts: vec![evidence_artifact],
            })
        };

        // =====================================================================
        // ONE COMMIT. `write_extra` runs INSIDE the canonical advance's
        // transaction, so the advance and the entire durable bundle — proposal,
        // gate, pending EK head, exact submission material, outbox row — land
        // together or not at all. There is no window in which a debit exists
        // without the record that drives its settlement.
        //
        // Every helper here MUST take the transaction: the global connection
        // mutex is already held, so anything that opens its own would deadlock.
        // =====================================================================
        let admission_plan = crate::sdk::core_sdk::AdmissionPlan {
            prepared: econ_prepared,
            storage_set_id: econ_set.id(),
            build: Box::new(|_o| {
                let parts = admission_parts.borrow();
                let parts = parts.as_ref().ok_or_else(|| {
                    dsm::types::error::DsmError::internal(
                        "admission parts missing at commit",
                        None::<std::convert::Infallible>,
                    )
                })?;
                Ok((parts.coords, parts.artifacts.clone()))
            }),
            accepted_out: &mut accepted_admission,
        };
        let (new_state, artifacts) = match self.wallet.send_transfer_op_staged_with_admission(
            signed_op,
            &signed_tx,
            build_online_send_artifacts,
            |tx, _outcome, artifacts: &OnlineSendArtifacts| {
                // ONE implementation, shared with the non-transactional wrapper the
                // tests use — so the tests exercise production's actual writes.
                crate::storage::client_db::commit_send_prerequisites_with_conn(
                    tx,
                    &artifacts.sender_proposal,
                    &artifacts.outbox_record,
                    &artifacts.submission_id,
                    &artifacts.ek_material.ek_pk,
                    &artifacts.ek_material.ek_sk,
                    &artifacts.ek_material.at_rest_key,
                    artifacts.ek_material.is_init,
                    &artifacts.extra_artifacts,
                )
                .map_err(|e| {
                    dsm::types::error::DsmError::internal(
                        format!("durable send bundle write failed: {e}"),
                        None::<std::io::Error>,
                    )
                })?;
                Ok(())
            },
            Some(admission_plan),
        ) {
            Ok(triple) => triple,
            Err(e) => {
                // Nothing was committed — the transaction rolled the advance back
                // with the bundle, and the builder runs before the write. There is
                // no durable state to unwind and nothing became deliverable.
                let failure_class = self.classify_local_state_update_failure(&e);
                log::error!("[wallet.send] staged send FAILED class={failure_class}: {e}");
                return err(format!("wallet.send: local state update failed: {e}"));
            }
        };

        let OnlineSendArtifacts {
            sender_proposal,
            outbox_record,
            submission_id,
            receipt_canonical_bytes,
            extra_artifacts,
            ..
        } = artifacts;
        // ── The debit is committed but HELD (correction A): finish the
        // admission — publish, register, validate, admit — and only the
        // terminal admission transaction promotes the outbox row to
        // deliverable. A failure here leaves everything resumable and
        // NOTHING delivered.
        let pending_admission = match accepted_admission {
            Some(p) => p,
            None => {
                return err(
                    "wallet.send: advance committed without an accepted admission".to_string(),
                )
            }
        };
        let econ_parts_final = match admission_parts.into_inner() {
            Some(p) => p,
            None => return err("wallet.send: admission parts missing".to_string()),
        };
        if let Err(e) = crate::sdk::economic_admission_flow::finish_admission(
            &self.core_sdk,
            &econ_network,
            &econ_set,
            &econ_validated,
            econ_parts_final.witness,
            econ_parts_final.manifest,
            admission_op,
            pending_admission,
            Vec::new(),
        )
        .await
        {
            return err(format!(
                "wallet.send: debit committed; economic admission is HELD for resume and \
                 nothing was delivered: {e}"
            ));
        }

        let mut b0x_succeeded = false;
        let mut b0x_message_id: Option<String> = None;

        // Duplicate-traffic suppression against the periodic sweep, which may
        // observe the row while this call is on the wire. Optimization only:
        // correctness rests on deterministic ids, frozen bytes, CAS status and
        // node-side dedup, and a concurrent double-drive is merely wasteful.
        let _in_flight = crate::storage::client_db::DeliveryInFlight::claim(
            &outbox_record.relationship_key,
            &outbox_record.canonical_parent,
            &outbox_record.proposal_nonce,
        );

        // Durably marked BEFORE entering the network call, so a crash
        // mid-call can never leave a row that merely LOOKS pre-submit. A mark
        // that does not land sends nothing: the row stays deliverable and the
        // reconciliation sweep drives it.
        if let Err(e) = crate::storage::client_db::set_sender_outbox_status(
            &outbox_record.relationship_key,
            &outbox_record.canonical_parent,
            &outbox_record.proposal_nonce,
            crate::storage::client_db::OUTBOX_SUBMITTING,
        ) {
            return err(format!(
                "wallet.send: debit committed; the outbox row could not be marked \
                 submitting, so nothing was sent and the transfer is retained for the \
                 reconciliation sweep: {e}"
            ));
        }

        // Create B0xSDK and submit (arg order: device_id, core_sdk, endpoints)
        let sender_b32_for_b0x = crate::util::text_id::encode_base32_crockford(&from_device_id);
        match crate::sdk::b0x_sdk::B0xSDK::new(
            sender_b32_for_b0x,
            self.core_sdk.clone(),
            storage_endpoints,
        ) {
            Ok(mut b0x_sdk) => {
                // ONE delivery operation for the WHOLE frozen logical send —
                // the transfer envelope AND every frozen A-side artifact —
                // under the ids and route they were frozen with. This is the
                // same call the recovery sweep makes, so first attempt and
                // retry cannot drift. It reports success only when every half
                // reached quorum; a transfer-only quorum is not delivery.
                //
                // No outer timeout: the transport bounds itself through its
                // retry schedule. An arbitrary deadline sized for one envelope
                // was how a still-viable quorum attempt got reported as
                // uncertain.
                let retry = crate::sdk::b0x_sdk::B0xRetryConfig::default();
                match b0x_sdk
                    .deliver_frozen_logical_send(&outbox_record, &extra_artifacts, &retry)
                    .await
                {
                    Ok(delivered) => {
                        log::info!(
                            "[wallet.send] ✅ Delivered frozen send to b0x: transfer={} artifacts={}",
                            delivered.transfer_id,
                            delivered.artifact_ids.len()
                        );
                        b0x_succeeded = true;
                        b0x_message_id = Some(delivered.transfer_id.clone());
                        // §16.6 proposal authority: bind the wire identity to
                        // the persisted proposal (exactly once). Guarded on
                        // `proposed` so a late completion can never drag a
                        // step that already finalized back to `submitted`.
                        match crate::storage::client_db::mark_sender_proposal_submitted_if_proposed(
                            &sender_proposal.relationship_key,
                            &sender_proposal.canonical_parent,
                            &submission_id,
                        ) {
                            Ok(true) => {}
                            Ok(false) => log::info!(
                                "[wallet.send] §16.6 proposal already past `proposed`; leaving it"
                            ),
                            Err(e) => log::error!(
                                "[wallet.send] §16.6 proposal message-id bind failed: {e}"
                            ),
                        }
                        // Wake our own inbox poller so we pick up the recipient's
                        // ACK faster — reduces tip-drift on subsequent sends.
                        crate::sdk::inbox_poller::resume_poller();
                        // Record network success for connectivity monitoring
                        // Backfill the receipt into the local transaction record
                        // so the sender's history shows "Verified" instead of "N/A".
                        if let Err(e) = crate::storage::client_db::update_transaction_proof_data(
                            &signed_tx.id,
                            &receipt_canonical_bytes,
                        ) {
                            log::warn!("[wallet.send] Failed to persist receipt locally: {}", e);
                        }
                    }
                    Err(e) => {
                        // Record network failure for connectivity monitoring

                        log::error!("[wallet.send] ❌ frozen send not fully delivered: {}", e);
                    }
                }
            }
            Err(e) => {
                // Record network failure for connectivity monitoring

                log::error!("[wallet.send] ❌ B0xSDK init failed: {}", e);
            }
        }

        // =====================================================================
        // ATOMIC ROLLBACK: If b0x delivery failed, restore canonical state,
        // shared SMT, persisted transaction/projection rows, and in-memory caches.
        // =====================================================================
        // =====================================================================
        // §16.6 DEFECT ZERO — FORWARD-ONLY AFTER THE DURABLE COMMIT.
        //
        // A submission failure here is NOT proof of non-delivery. A quorum may
        // have accepted the envelope while the response was lost, the socket
        // timed out, or the process was killed. Rolling the debit back on that
        // evidence is exactly how a creditable message ends up stranded against
        // restored funds — the live hazard this work exists to remove.
        //
        // So the debit, proposal, gate, pending EK head and outbox row all
        // STAY. The row moves to `submission_uncertain` and the reconciliation
        // sweep resubmits the byte-identical stored envelope; the node's
        // UNIQUE(message_id) makes that idempotent.
        // =====================================================================
        // Both status writes below are compare-and-set FROM `submitting`. While
        // this call was on the wire the recipient may already have accepted and
        // replied, and a concurrent storage.sync may have finalized the row to
        // `gc_pending`; an unconditional write here would drag it back and
        // strand it outside both the unsettled set and the GC set.
        if !b0x_succeeded {
            if let Err(e) = crate::storage::client_db::advance_sender_outbox_status_if(
                &outbox_record.relationship_key,
                &outbox_record.canonical_parent,
                &outbox_record.proposal_nonce,
                &[crate::storage::client_db::OUTBOX_SUBMITTING],
                crate::storage::client_db::OUTBOX_SUBMISSION_UNCERTAIN,
            ) {
                log::error!(
                    "[wallet.send] could not record submission_uncertain; the row stays \
                     submitting and the sweep resubmits it: {e}"
                );
            }
            log::warn!(
                "[wallet.send] §16.6 submission outcome UNKNOWN — retaining debit, gate and \
                 outbox; reconciling forward (a timeout is not proof of non-delivery)"
            );
            return err(
                "wallet.send: delivery outcome unknown — the transfer is retained and will be \
                 retried automatically. Funds are not lost; do not resend."
                    .to_string(),
            );
        }
        if let Err(e) = crate::storage::client_db::advance_sender_outbox_status_if(
            &outbox_record.relationship_key,
            &outbox_record.canonical_parent,
            &outbox_record.proposal_nonce,
            &[crate::storage::client_db::OUTBOX_SUBMITTING],
            crate::storage::client_db::OUTBOX_SUBMITTED,
        ) {
            log::error!(
                "[wallet.send] delivered, but could not record submitted; the row stays \
                 submitting and the sweep resubmits it (the node deduplicates): {e}"
            );
        }

        // Record a single outstanding online transition for this relationship.
        // The shared contact tip remains at h_n until the recipient ACKs the prior
        // message; only the sender's local restore tip advances to h_{n+1}.
        {
            // The gate is ALREADY durable — it was committed atomically with the
            // proposal, the pending EK head and the outbox row before anything
            // was submitted. Nothing here may fail the transfer: the two former
            // rollback sites (missing message id, gate-persist failure) are gone
            // because neither is evidence that the message was not delivered.
            //
            // The returned storage message id is GC metadata ONLY. Finalization
            // keys on the receipt commitment, so a missing or unbindable id
            // costs nothing but a later spool cleanup.
            let new_tip_b32 =
                crate::util::text_id::encode_base32_crockford(&outbox_record.projection_target);
            match b0x_message_id {
                Some(ref msg_id) => {
                    if let Err(e) = crate::storage::client_db::bind_sender_outbox_message_ids(
                        &outbox_record.relationship_key,
                        &outbox_record.canonical_parent,
                        &outbox_record.proposal_nonce,
                        msg_id,
                    ) {
                        log::warn!(
                            "[wallet.send] §16.6 message-id bind failed (GC metadata only, \
                             transfer unaffected): {e}"
                        );
                    }
                }
                None => log::warn!(
                    "[wallet.send] §16.6 no storage message id returned — transfer stands \
                     (finalization keys on the receipt commitment); spool GC will rely on \
                     the deterministic submission id"
                ),
            }
            log::info!(
                "[wallet.send] §16.6 Pending online transition already durable: parent={} next={}",
                &crate::util::text_id::encode_base32_crockford(&chain_tip_arr)[..8],
                &new_tip_b32[..8]
            );
            // Keep in-memory bilateral_chains cache on the sender's local successor tip so
            // the app state matches the optimistic local transition. The persisted pending
            // online outbox gate blocks the next send until the recipient catches up.
            if let Err(e) = self.wallet.update_bilateral_chain_tip(
                &to_device_id_str,
                &new_tip_b32,
                &new_tip_b32,
                0,
            ) {
                log::warn!(
                    "[wallet.send] §16.6 In-memory bilateral_chains cache sync failed: {}",
                    e
                );
            }
            // Canonical contacts.chain_tip stays at T_n. Only local_bilateral_chain_tip
            // was advanced to T_{n+1} by record_pending_online_transition above.
            // The pending-gate interlock requires ACK or storage.sync finalization
            // before the canonical tip advances, keeping recipient polling aligned
            // with the sender's actual finalized relationship tip.
        }

        // Get new balance for response
        let new_balance = match self.wallet.get_balance(&token_id) {
            Ok(bal) => Some(bal.value()),
            Err(e) => {
                log::error!(
                    "[wallet.send] committed, but the post-send {token_id} balance could not be \
                     read: {e}"
                );
                None
            }
        };

        let response = generated::OnlineTransferResponse {
            success: true,
            transaction_hash: Some(generated::Hash32 {
                v: new_state.hash.to_vec(),
            }),
            message: "Transfer successful".to_string(),
            new_balance,
        };
        // NEW: Return as Envelope.onlineTransferResponse (field 40)
        pack_envelope_ok(generated::envelope::Payload::OnlineTransferResponse(
            response,
        ))
    }

    // Helper: Shared logic for OnlineMessageRequest processing
    pub(crate) async fn process_online_message_logic(
        &self,
        msg_req: generated::OnlineMessageRequest,
    ) -> AppResult {
        // Check network connectivity before attempting online message send
        let Ok(from_device_id) = <[u8; 32]>::try_from(msg_req.from_device_id.as_slice()) else {
            return err("message.send: from_device_id must be 32 bytes".into());
        };
        let Ok(to_device_id) = <[u8; 32]>::try_from(msg_req.to_device_id.as_slice()) else {
            return err("message.send: to_device_id must be 32 bytes".into());
        };
        let Ok(chain_tip_arr) = <[u8; 32]>::try_from(msg_req.chain_tip.as_slice()) else {
            return err("message.send: chain_tip must be 32 bytes".into());
        };

        let memo = msg_req.memo.clone();

        let nonce = dsm::envelope::compute_online_message_nonce_v3(
            &from_device_id,
            &to_device_id,
            &chain_tip_arr,
            &msg_req.payload,
            &memo,
        );

        if msg_req.nonce.len() == 32 && msg_req.nonce.as_slice() != nonce.as_slice() {
            return err("message.send: nonce mismatch".into());
        }

        let signing_bytes = dsm::envelope::compute_online_message_signing_bytes_v3(
            &from_device_id,
            &to_device_id,
            &chain_tip_arr,
            &nonce,
            &msg_req.payload,
            &memo,
        );

        let canonical_signature = match self.wallet.sign_operation_bytes(&signing_bytes) {
            Ok(sig) => sig,
            Err(e) => return err(format!("message.send: canonical signing failed: {e}")),
        };

        let to_device_id_str = crate::util::text_id::encode_base32_crockford(&to_device_id);
        let sender_genesis = match self.core_sdk.local_genesis_hash().await {
            Ok(genesis) if genesis.len() == 32 => genesis,
            Ok(genesis) => {
                return err(format!(
                    "message.send: local genesis is {} bytes, not 32",
                    genesis.len()
                ))
            }
            Err(e) => return err(format!("message.send: local genesis unavailable: {e}")),
        };
        let sender_genesis_b32 = crate::util::text_id::encode_base32_crockford(&sender_genesis);
        let sender_chain_tip_b32 = crate::util::text_id::encode_base32_crockford(&chain_tip_arr);
        let sender_signing_public_key = match crate::sdk::signing_authority::current_public_key() {
            Ok(pk) => pk,
            Err(e) => {
                return err(format!(
                    "message.send: cannot retrieve signing authority public key: {e}"
                ));
            }
        };

        let recipient_genesis_raw: [u8; 32] =
            match crate::storage::client_db::get_contact_by_device_id(&to_device_id) {
                Ok(Some(contact)) => match <[u8; 32]>::try_from(contact.genesis_hash.as_slice()) {
                    Ok(genesis) => genesis,
                    Err(e) => {
                        return err(format!(
                            "message.send: the recipient contact's genesis is not 32 bytes: {e}"
                        ))
                    }
                },
                Ok(None) => return err("message.send: the recipient is not a contact".into()),
                Err(e) => return err(format!("message.send: contact lookup failed: {e}")),
            };
        let recipient_genesis_b32 =
            crate::util::text_id::encode_base32_crockford(&recipient_genesis_raw);

        let storage_endpoints = match crate::sdk::storage_set::pinned_endpoints() {
            Ok(endpoints) => endpoints,
            Err(e) => return err(format!("message.send: no pinned storage set: {e}")),
        };

        let msg_op = dsm::types::operations::Operation::Generic {
            operation_type: b"online.message".to_vec(),
            data: msg_req.payload.clone(),
            message: memo.clone(),
            signature: vec![],
        };

        // §16.4: Compute tip-scoped b0x routing address for message delivery.
        let routing_address = match crate::sdk::b0x_sdk::B0xSDK::compute_b0x_address(
            &recipient_genesis_raw,
            &to_device_id,
            &chain_tip_arr,
        ) {
            Ok(addr) => addr,
            Err(e) => return err(format!("message.send: b0x address rotation failed: {e}")),
        };

        let b0x_params = crate::sdk::b0x_sdk::B0xSubmissionParams {
            submission_id: None,
            recipient_device_id: to_device_id_str.clone(),
            recipient_genesis_hash: recipient_genesis_b32,
            transaction: msg_op,
            signature: canonical_signature,
            sender_genesis_hash: sender_genesis_b32,
            sender_chain_tip: sender_chain_tip_b32,
            sender_signing_public_key,
            routing_address,
            canonical_operation_bytes: Vec::new(),
            receipt_evidence_digest: Vec::new(),
            sender_economic_position: 0,
            sender_debit_mutation_index: 0,
        };

        let sender_device_id_b32 = crate::util::text_id::encode_base32_crockford(&from_device_id);
        let mut b0x_sdk = match crate::sdk::b0x_sdk::B0xSDK::new(
            sender_device_id_b32,
            self.core_sdk.clone(),
            storage_endpoints,
        ) {
            Ok(sdk) => sdk,
            Err(e) => {
                return err(format!("message.send: b0x init failed: {e}"));
            }
        };
        let msg_id = match b0x_sdk.submit_to_b0x(b0x_params).await {
            Ok(mid) => mid,
            Err(e) => {
                return err(format!("message.send: b0x submit failed: {e}"));
            }
        };

        let Some(msg_id_bytes) = crate::util::text_id::decode_base32_crockford(&msg_id) else {
            return err(format!(
                "message.send: the spool returned a message id that is not Base32: {msg_id}"
            ));
        };
        let response = generated::OnlineMessageResponse {
            success: true,
            message: "Message queued".to_string(),
            message_id: msg_id_bytes,
        };

        // NEW: Return as Envelope.onlineMessageResponse (field 41)
        pack_envelope_ok(generated::envelope::Payload::OnlineMessageResponse(
            response,
        ))
    }
}

fn compute_initial_relationship_chain_tip(
    local_device_id: [u8; 32],
    local_genesis: [u8; 32],
    remote_device_id: &[u8],
    remote_genesis: &[u8],
) -> Option<[u8; 32]> {
    let remote_device: [u8; 32] = remote_device_id.try_into().ok()?;
    let remote_genesis: [u8; 32] = remote_genesis.try_into().ok()?;
    Some(
        dsm::core::bilateral_transaction_manager::initial_relationship_chain_tip(
            &local_device_id,
            &local_genesis,
            &remote_device,
            &remote_genesis,
        ),
    )
}

pub(crate) fn relationship_tip_for_contact_restore(
    local_device_id: [u8; 32],
    local_genesis: [u8; 32],
    contact: &crate::storage::client_db::ContactRecord,
) -> Option<[u8; 32]> {
    if let Some(stored_tip) = contact.current_chain_tip.as_deref() {
        if stored_tip.len() == 32 {
            let mut tip = [0u8; 32];
            tip.copy_from_slice(stored_tip);
            return Some(tip);
        }
    }

    compute_initial_relationship_chain_tip(
        local_device_id,
        local_genesis,
        &contact.device_id,
        &contact.genesis_hash,
    )
}

/// Route freshness tag for stale-route delivery root.
/// `Current` = derived from the contact's current chain tip.
/// `PreviousTip` = derived from the predecessor tip (bounded lookback of 1).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum RouteFreshness {
    Current,
    PreviousTip,
}

/// A B0x inbox address tagged with its derivation freshness.
#[derive(Debug, Clone)]
pub(crate) struct TaggedInboxAddress {
    pub address: String,
    pub freshness: RouteFreshness,
}

/// Collect per-contact B0x addresses tagged with route freshness.
///
/// Returns up to TWO addresses per contact:
/// 1. Current tip address (always, tagged `Current`)
/// 2. Previous tip address (if stored, non-zero, and different from current; tagged `PreviousTip`)
///
/// This enables stale-route delivery: messages sent to a previous tip's address
/// become visible but are NOT auto-applied to wallet state.
pub(crate) fn collect_tagged_inbox_addresses(
    local_genesis: [u8; 32],
    local_device_id: [u8; 32],
    contacts: &[crate::storage::client_db::ContactRecord],
) -> Vec<TaggedInboxAddress> {
    if local_genesis == [0u8; 32] {
        log::warn!(
            "[collect_tagged_inbox_addresses] genesis is ZERO — returning empty address list"
        );
        return Vec::new();
    }

    let mut addresses = Vec::with_capacity(contacts.len() * 2);

    for contact in contacts {
        let restored_tip =
            relationship_tip_for_contact_restore(local_device_id, local_genesis, contact);
        let tip_status = match restored_tip {
            Some(tip) if tip == [0u8; 32] => "zero",
            Some(_) => "restored",
            None => "missing",
        };
        log::info!(
            "[collect_tagged_inbox_addresses] contact={} tip_status={} device_prefix={}",
            contact.alias,
            tip_status,
            crate::util::text_id::encode_base32_crockford(
                &contact.device_id[..8.min(contact.device_id.len())]
            )
            .get(..8)
            .unwrap_or("?"),
        );

        let Some(current_tip) = restored_tip else {
            log::warn!(
                "[collect_tagged_inbox_addresses] contact {} has no valid canonical relationship tip",
                contact.alias
            );
            continue;
        };

        // DIAGNOSTIC: mirror wallet.send §16.4 inputs for cross-device comparison
        log::info!(
            "[collect_tagged_inbox_addresses] contact={} genesis={}.. device={}.. tip={}.. (tip_zero={})",
            contact.alias,
            crate::util::text_id::encode_base32_crockford(&local_genesis).get(..8).unwrap_or("?"),
            crate::util::text_id::encode_base32_crockford(&local_device_id).get(..8).unwrap_or("?"),
            crate::util::text_id::encode_base32_crockford(&current_tip).get(..8).unwrap_or("?"),
            current_tip == [0u8; 32],
        );

        // 1. Current tip address (always)
        match crate::sdk::b0x_sdk::B0xSDK::compute_b0x_address(
            &local_genesis,
            &local_device_id,
            &current_tip,
        ) {
            Ok(addr) => {
                log::info!(
                    "[collect_tagged_inbox_addresses] contact={} addr={}",
                    contact.alias,
                    &addr[..16.min(addr.len())],
                );
                addresses.push(TaggedInboxAddress {
                    address: addr,
                    freshness: RouteFreshness::Current,
                });
            }
            Err(e) => {
                log::warn!(
                    "[collect_tagged_inbox_addresses] contact {} current-tip address derivation failed: {}",
                    contact.alias,
                    e
                );
            }
        }

        // 2. Previous tip address (bounded lookback of 1)
        if let Some(prev_tip_bytes) = contact.previous_chain_tip.as_deref() {
            if prev_tip_bytes.len() == 32 && prev_tip_bytes != [0u8; 32] {
                let mut prev_tip = [0u8; 32];
                prev_tip.copy_from_slice(prev_tip_bytes);
                if prev_tip != current_tip {
                    match crate::sdk::b0x_sdk::B0xSDK::compute_b0x_address(
                        &local_genesis,
                        &local_device_id,
                        &prev_tip,
                    ) {
                        Ok(addr) => {
                            log::info!(
                                "[collect_tagged_inbox_addresses] contact {} stale-route address added (previous tip)",
                                contact.alias
                            );
                            addresses.push(TaggedInboxAddress {
                                address: addr,
                                freshness: RouteFreshness::PreviousTip,
                            });
                        }
                        Err(e) => {
                            log::warn!(
                                "[collect_tagged_inbox_addresses] contact {} previous-tip address derivation failed: {}",
                                contact.alias,
                                e
                            );
                        }
                    }
                }
            }
        }

        // 3. Pending-outbox next_tip address.
        //
        // When this device has a pending online outbox for `contact` (i.e. we sent
        // an online transfer that the counterparty hasn't yet ACKed), `record_pending_
        // online_transition` advances `contacts.local_bilateral_chain_tip` to T_{n+1}
        // without touching `current_chain_tip`. The counterparty sees our local tip as
        // T_{n+1} and will therefore deposit any reply using:
        //   compute_b0x_address(our_genesis, our_device_id, T_{n+1})
        //
        // But `current_chain_tip` still holds T_n, so address (1) above would miss it.
        // Adding the pending next_tip as a live `Current` address closes this gap.
        if contact.device_id.len() == 32 {
            if let Ok(Some(pending)) =
                crate::storage::client_db::get_pending_online_outbox(&contact.device_id)
            {
                if pending.next_tip.len() == 32 {
                    let mut next_tip = [0u8; 32];
                    next_tip.copy_from_slice(&pending.next_tip);
                    if next_tip != current_tip && next_tip != [0u8; 32] {
                        match crate::sdk::b0x_sdk::B0xSDK::compute_b0x_address(
                            &local_genesis,
                            &local_device_id,
                            &next_tip,
                        ) {
                            Ok(addr) => {
                                log::info!(
                                    "[collect_tagged_inbox_addresses] contact {} pending-outbox next-tip address added (T_n+1 reply window)",
                                    contact.alias
                                );
                                addresses.push(TaggedInboxAddress {
                                    address: addr,
                                    freshness: RouteFreshness::Current,
                                });
                            }
                            Err(e) => {
                                log::warn!(
                                    "[collect_tagged_inbox_addresses] contact {} pending-outbox next-tip address derivation failed: {}",
                                    contact.alias,
                                    e
                                );
                            }
                        }
                    }
                }
            }
        }
    }

    // 4. Retained routes from incomplete or unACKed split-transfer staging.
    //
    // A split send's two halves may land polls — or relationship advancements
    // — apart. Sources 1-3 hold a route for one advancement at most, and a
    // partner artifact replayed by the sender under its ORIGINAL frozen route
    // (it is never re-routed: the node dedups on message id alone) would land
    // where nobody is listening. So the route the first half arrived on stays
    // in the poll set until the pair completes and both ACKs succeed. Read from
    // the database every poll, so it survives restart. `Current`, not
    // `PreviousTip`: the previous-tip adjacency filter would drop or mis-ACK a
    // split half. Dedup below folds it into any live route it collides with.
    match crate::storage::client_db::recipient_staging::retained_routes_for_polling() {
        Ok(routes) => {
            for route in routes {
                log::info!(
                    "[collect_tagged_inbox_addresses] retained split-transfer route added {}..",
                    &route[..route.len().min(12)]
                );
                addresses.push(TaggedInboxAddress {
                    address: route,
                    freshness: RouteFreshness::Current,
                });
            }
        }
        Err(e) => log::warn!(
            "[collect_tagged_inbox_addresses] retained-route lookup failed (continuing with \
             tip-derived routes only): {e}"
        ),
    }

    // Dedup by address: if current and previous collide, keep Current
    addresses.sort_by(|a, b| a.address.cmp(&b.address));
    addresses.dedup_by(|a, b| {
        if a.address == b.address {
            // Keep whichever is Current
            if a.freshness == RouteFreshness::Current {
                b.freshness = RouteFreshness::Current;
            }
            true
        } else {
            false
        }
    });
    addresses
}

/// Outcome of the pure contact-repair trust decision.
enum ContactRepair {
    /// The pinned contact already matches the directory entry — nothing to persist.
    Unchanged(crate::storage::client_db::ContactRecord),
    /// The Kyber key was refreshed under the pinned AK — the caller must persist this.
    Repaired(crate::storage::client_db::ContactRecord),
}

/// Reconcile a device's directory entry against its pinned contact, WITHOUT any
/// I/O.
///
/// The pairing-established AK (`contact_record.public_key`) is the trust root.
/// The entry has already proved itself (`device_directory::read_entry`: its AK
/// hashes to the device id with its AttA, and that AK signed it, Kyber key
/// included). An entry whose AK is not the pinned AK, or that names another
/// genesis or device, is a substitution and is refused — the caller's
/// persistence step is unreachable on that path, so the pinned contact is left
/// untouched. A permitted repair refreshes only the Kyber key the entry signs.
fn repair_contact_decision(
    mut contact_record: crate::storage::client_db::ContactRecord,
    entry: &dsm::core::identity::directory::DirectoryEntry,
) -> Result<ContactRepair, String> {
    if entry.body.ak_public_key != contact_record.public_key {
        return Err(
            "the device's directory entry names another AK than the pairing-established contact \
             AK — rejecting (possible substitution/equivocation)"
                .to_string(),
        );
    }
    if entry.body.genesis.as_slice() != contact_record.genesis_hash.as_slice()
        || entry.body.device_id.as_slice() != contact_record.device_id.as_slice()
    {
        return Err("the directory entry names another identity than the contact".to_string());
    }
    if contact_record.kyber_public_key == entry.body.kyber_public_key {
        return Ok(ContactRepair::Unchanged(contact_record));
    }
    contact_record.kyber_public_key = entry.body.kyber_public_key.clone();
    contact_record.verified = true;
    contact_record.needs_online_reconcile = false;
    Ok(ContactRepair::Repaired(contact_record))
}

#[cfg(test)]
