/// A counterparty a contact QR named, as its own directory entry proves it.
pub(crate) struct ResolvedCounterparty {
    /// The entry the device signed with its AK: its genesis, device id, AK and
    /// Kyber key.
    pub entry: dsm::core::identity::directory::DirectoryEntry,
    /// The members of the pinned set that hold exactly this entry.
    pub verifying_nodes: Vec<dsm::types::identifiers::NodeId>,
}

/// Resolve a ContactQrV3 through the device directory: the entry at the named
/// device's cell that proves itself, whose AK is the key the QR presents, held
/// by at least [`STORAGE_FINALITY_COUNT`] members of the pinned set.
///
/// [`STORAGE_FINALITY_COUNT`]: dsm::sofi::wire::STORAGE_FINALITY_COUNT
pub(crate) async fn resolve_counterparty_via_transport(
    qr: &generated::ContactQrV3,
) -> Result<ResolvedCounterparty, String> {
    let device_id = <[u8; 32]>::try_from(qr.device_id.as_slice()).map_err(|e| {
        format!(
            "ContactQrV3: device_id must be 32 bytes (got {}): {e}",
            qr.device_id.len()
        )
    })?;
    let genesis_hash = <[u8; 32]>::try_from(qr.genesis_hash.as_slice()).map_err(|e| {
        format!(
            "ContactQrV3: genesis_hash must be 32 bytes (got {}): {e}",
            qr.genesis_hash.len()
        )
    })?;
    if qr.signing_public_key.is_empty() {
        return Err("ContactQrV3: signing_public_key missing".to_string());
    }

    let network = crate::sdk::economic_admission_flow::committed_network_id()
        .map_err(|e| format!("no committed network: {e}"))?;
    let set = crate::sdk::storage_set::canonical_set(&network)
        .map_err(|e| format!("no pinned storage set: {e}"))?;
    let read = crate::sdk::device_directory::read_entry(&set, &genesis_hash, &device_id)
        .await
        .map_err(|e| format!("directory read failed: {e}"))?
        .ok_or_else(|| {
            "no member of the pinned set holds a directory entry for this device that proves \
             itself"
                .to_string()
        })?;
    decide_counterparty(&qr.signing_public_key, read)
}

/// The trust decision over a directory read, apart from the I/O: the entry's
/// AK must be the key the QR presents, and enough members must hold it.
fn decide_counterparty(
    presented_ak: &[u8],
    read: crate::sdk::device_directory::DirectoryRead,
) -> Result<ResolvedCounterparty, String> {
    if read.entry.body.ak_public_key != presented_ak {
        return Err(
            "the device's directory entry names another AK than the contact QR presents — \
             rejecting (possible substitution)"
                .to_string(),
        );
    }
    let required = dsm::sofi::wire::STORAGE_FINALITY_COUNT;
    if read.holders.len() < required {
        return Err(format!(
            "{} members of the pinned set hold the device's directory entry; {required} needed",
            read.holders.len()
        ));
    }
    Ok(ResolvedCounterparty {
        entry: read.entry,
        verifying_nodes: read
            .holders
            .into_iter()
            .map(dsm::types::identifiers::NodeId::new)
            .collect(),
    })
}

