//! CLASS-1 CONFORMANCE VECTORS FOR THE DLV SUCCESSOR DERIVATION.
//!
//! Amendment 2c-C2 ruling D: a class-1 vector's expected bytes are produced
//! WITHOUT the production encoder, decoder or digest helper under test. Here
//! the parent is a fixed `VaultStateV2`, the successor is what the frozen
//! predicate (`derive_market_successor`, `derive_close_successor`) derives from
//! it, and the expected bytes are the INDEPENDENT encoder's rendering of that
//! successor -- pinned as literals a foreign implementation can compare
//! against without holding this repository's build.
//!
//! Two things are checked per vector, and they are different checks:
//!   1. the derivation lands on the pinned bytes (the predicate is frozen);
//!   2. the production encoder agrees with the independent one on the derived
//!      state (the encoding is frozen).
//!
//! A change to either the derivation or the encoding turns exactly one of them
//! red, which is what makes the failure legible.

#[path = "common/indep_ccb.rs"]
mod indep;

use dsm::ccb::{
    vault_state_commitment, EncumbranceSet, FeePolicy, MarketPolicy, ReleasePolicy,
    StorageSetMembers, VaultStateV2,
};
use dsm::dlv::successor_validity::{
    derive_close_successor, derive_market_successor, DeriveExpected, MarketTerms,
};

fn d(b: u8) -> [u8; 32] {
    [b; 32]
}
const VAULT_ID: [u8; 32] = [0x7E; 32];
const TOKEN_A: [u8; 32] = [0x11; 32];
const TOKEN_B: [u8; 32] = [0x22; 32];
/// Deliberately not in id order, with incarnations that do NOT co-sort with
/// the ids — the same fixture `ccb_conformance.rs` uses, so a pair-sorting
/// encoder is caught here too.
const MEMBERS: [(&[u8], [u8; 32]); 5] = [
    (b"dsm-node-3", [0x31; 32]),
    (b"dsm-node-1", [0x95; 32]),
    (b"dsm-node-5", [0x07; 32]),
    (b"dsm-node-2", [0xF2; 32]),
    (b"dsm-node-4", [0x64; 32]),
];

/// The same parent `ccb_conformance.rs` freezes, so the two vector files
/// describe one object.
fn parent(generation: u64, r_a: u64, r_b: u64, h_n: [u8; 32], beta: Option<u64>) -> VaultStateV2 {
    VaultStateV2 {
        owner_genesis_id: d(0xA1),
        owner_device_id: d(0xA2),
        vault_id: VAULT_ID,
        generation,
        reserve_a: r_a,
        reserve_b: r_b,
        market_policy: MarketPolicy::beta_constant_product(TOKEN_A, TOKEN_B).expect("ordered pair"),
        release_policy: ReleasePolicy::beta_owner_local_full_close(),
        fee_policy: FeePolicy::new(30).expect("30 bps"),
        encumbrances: EncumbranceSet::empty(),
        iteration_budget: beta,
        parent_state_commitment: h_n,
        owner_authority_transition_digest: d(0xA3),
        storage_set: StorageSetMembers::new(&MEMBERS).expect("five distinct members"),
        quorum: 4,
    }
}

/// The independent encoder's rendering of a state with this fixture's fixed
/// identity, policies and set.
fn indep_bytes(v: &VaultStateV2) -> Vec<u8> {
    let entries: Vec<(Vec<u8>, [u8; 32])> = MEMBERS
        .iter()
        .map(|(id, inc)| (id.to_vec(), *inc))
        .collect();
    indep::vault_state(
        d(0xA1),
        d(0xA2),
        VAULT_ID,
        v.generation,
        v.reserve_a,
        v.reserve_b,
        indep::market_policy(1, 1, TOKEN_A, TOKEN_B),
        indep::release_policy(1, 1),
        indep::fee_policy(30),
        indep::encumbrance_set(Vec::new()),
        v.iteration_budget,
        v.parent_state_commitment,
        d(0xA3),
        indep::storage_set(entries),
        4,
    )
}

